//! 再計算器 — 未再計算の祖先を集め、トポロジカル順に各1回だけ評価する。
//!
//! ## 遅延と差分と glitch-free
//!
//! [`crate::ComputeGraph::set_input`] は値の書き込みと未再計算印の伝播しか行わず、
//! 実際の再計算はここまで遅延する。集めるのは「未再計算な祖先」だけなので影響外の
//! ノードは動かない (差分)。集めた後にトポロジカル順へ並べ替えてから評価するため、
//! ダイヤモンド依存でも各ノードちょうど1回しか評価されず、途中の食い違った値が
//! 見えることもない (glitch-free)。
//!
//! ## 祖先を遡り切らなくてよい理由
//!
//! このグラフの不変条件として、未再計算でないノードの依存は全て未再計算でない。
//! [`crate::ComputeGraph::set_input`] が入力の変更と同時にその影響先全体を未再計算に
//! するので、ある依存が未再計算になった瞬間そのノードも必ず一緒に未再計算になって
//! いる。よって未再計算でないノードに触れた時点でそれ以上遡らなくてよい。

use std::collections::HashSet;

use super::dependency_structure::依存構造;
use super::evaluation_state::評価状態;
use super::node_table::計算ノード表;

/// 再計算の実行者。読むだけの2部品と書き換える評価状態を借りて保持する。
pub(in crate::compute) struct 再計算器<'a, V> {
    ノード表: &'a 計算ノード表<V>,
    依存構造: &'a 依存構造,
    評価状態: &'a mut 評価状態<V>,
}

impl<'a, V> 再計算器<'a, V> {
    pub(in crate::compute) fn 部品を借りて始める(
        ノード表: &'a 計算ノード表<V>,
        依存構造: &'a 依存構造,
        評価状態: &'a mut 評価状態<V>,
    ) -> Self {
        Self {
            ノード表,
            依存構造,
            評価状態,
        }
    }

    /// `キー` が未再計算なら、その未再計算な祖先 (`キー` 自身を含む) をすべて
    /// トポロジカル順に評価する。既に再計算済みなら何もしない。
    pub(in crate::compute) fn 必要なら実行する(&mut self, キー: &str) {
        if !self.評価状態.未再計算か(キー) {
            return;
        }

        let mut 評価順: Vec<String> = Vec::new();
        let mut 走査済み: HashSet<String> = HashSet::new();
        self.未再計算の祖先を集める(キー, &mut 走査済み, &mut 評価順);

        評価順.sort_by_key(|キー| self.依存構造.トポロジカル位置(キー));

        for 評価するキー in 評価順 {
            self.キーの値を評価して書き込む(&評価するキー);
        }
    }

    /// `キー` から依存を遡って未再計算な祖先集合 (`キー` 自身を含む) を集める。
    /// `走査済み` は多重経路 (ダイヤモンド依存) での重複走査を防ぐメモ化集合。
    fn 未再計算の祖先を集める(
        &self,
        キー: &str,
        走査済み: &mut HashSet<String>,
        評価順: &mut Vec<String>,
    ) {
        if !走査済み.insert(キー.to_string()) {
            return;
        }
        if !self.評価状態.未再計算か(キー) {
            return;
        }
        for 依存 in self.ノード表.依存キー列(キー) {
            self.未再計算の祖先を集める(依存, 走査済み, 評価順);
        }
        評価順.push(キー.to_string());
    }

    /// 依存値を宣言順に集めて計算ノードを評価し、値を書き込んで再計算済みにする。
    /// 入力ノードは計算されないので何もしない。
    fn キーの値を評価して書き込む(&mut self, キー: &str) {
        let 依存値 = self.評価状態.依存値を集める(self.ノード表.依存キー列(キー));
        let Some(新しい値) = self.ノード表.依存値から計算する(キー, &依存値)
        else {
            return;
        };
        self.評価状態.計算結果を書き込む(キー, 新しい値);
    }
}
