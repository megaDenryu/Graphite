//! 計算グラフのノード種別 — 入力ノードと計算ノードの区別、および計算の中身を所有する。

/// 計算ノードが依存値の並びから自分の値を求める関数。
///
/// 動的ディスパッチ (`dyn Fn`) を使うのは、利用者が任意個・任意型の計算ノードを
/// 実行時に組み立てられるためであり、手書きでも同じ設計になる
/// (`docs/design_principles.md` 原則5 が禁じるのはマクロ生成コードへの混入であって、
/// ランタイムエンジン自身の設計判断とは階層が違う。モジュール doc の設計決定を参照)。
pub(in crate::compute) struct 値を求める関数<V>(依存値を受け取る処理<V>);

/// [`値を求める関数`] が内部に持つ、依存値の並びを受け取って値を返す処理そのもの。
type 依存値を受け取る処理<V> = Box<dyn Fn(&[&V]) -> V>;

impl<V> 値を求める関数<V> {
    pub(in crate::compute) fn 関数から生成する(f: impl Fn(&[&V]) -> V + 'static) -> Self {
        Self(Box::new(f))
    }

    pub(in crate::compute) fn 依存値から求める(&self, 依存値: &[&V]) -> V {
        (self.0)(依存値)
    }
}

/// ノードの種別。入力ノードは値のみ、計算ノードは依存キー列と関数を持つ。
pub(in crate::compute) enum ノード種別<V> {
    /// 入力ノード。値は [`crate::ComputeGraph::set_input`] で直接書き込む。
    入力ノード,
    /// 計算ノード。`依存キー列` は宣言順の依存キー列 (位置引数の並びそのもの)、
    /// `値を求める` はその値列から自分の値を求める関数。
    計算ノード {
        依存キー列: Vec<String>,
        値を求める: 値を求める関数<V>,
    },
}
