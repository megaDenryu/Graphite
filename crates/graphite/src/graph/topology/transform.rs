//! トポロジーの作り直し — 写した先のトポロジーと、変換前後の位置の対応を所有する。

use super::position::{ノード位置, 位置対応表};
use super::有向トポロジー;

/// ノードを1つずつ写して新しいトポロジーを組み立てる途中状態。写されなかった
/// ノードは位置の対応に載らないため、両端が残った辺だけを選んで写せる。
pub(in crate::graph) struct トポロジーの作り直し<N, E> {
    新しいトポロジー: 有向トポロジー<N, E>,
    位置の対応: 位置対応表,
}

impl<N, E> トポロジーの作り直し<N, E> {
    pub(in crate::graph) fn 空から始める() -> Self {
        Self {
            新しいトポロジー: 有向トポロジー::空のトポロジーを生成する(),
            位置の対応: 位置対応表::空の対応表を生成する(),
        }
    }

    /// 変換前の位置にあったノードを、新しい値として写す。写した順がそのまま
    /// 新しいトポロジーの挿入順になる。
    pub(in crate::graph) fn ノードを写す(
        &mut self,
        変換前: ノード位置,
        新しい値: N,
    ) -> ノード位置 {
        let 変換後 = self.新しいトポロジー.ノードを追加する(新しい値);
        self.位置の対応.対応を記録する(変換前, 変換後);
        変換後
    }

    /// 元のトポロジーの辺のうち、両端が写されたものだけを元の並び順で写す。
    pub(in crate::graph) fn 両端が残った辺を写す<M>(
        &mut self, 元: &有向トポロジー<M, E>
    ) where
        E: Clone,
    {
        for (始点, 終点, 値) in 元.辺の一覧() {
            if let (Some(新しい始点), Some(新しい終点)) = (
                self.位置の対応.変換後の位置(始点),
                self.位置の対応.変換後の位置(終点),
            ) {
                self.新しいトポロジー
                    .辺を追加する(新しい始点, 新しい終点, 値.clone());
            }
        }
    }

    pub(in crate::graph) fn 完成させる(self) -> 有向トポロジー<N, E> {
        self.新しいトポロジー
    }
}
