//! このファイルは、無向辺が未知の端点キーを参照したときの診断文を4通りの
//! 組み合わせで固定する。
//!
//! 生成側が両端のどちらを先に検査するかへ試験を依存させないため、この試験は
//! 自己ループで確かめる。第2端点の検査経路は `tests/undirected_edges.rs` が持つ。

use crate::{
    構築に失敗させる, 生成キーの地点のキーを作る, 利用者が宣言した地点キー, 利用者が宣言した経路キー,
    診断,
};

#[test]
fn 無向の端点も辺idも生成id型なら両方の綴りを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの交友(
            診断::生成キーの交友Id("経路0".into()),
            診断::生成キーの交友::new(生成キーの地点のキーを作る("ミオ"), 生成キーの地点のキーを作る("ミオ")),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキー 生成キーの地点Id(\"ミオ\") が 生成キーの地点 として見つかりません \
         (辺 `生成キーの交友` 生成キーの交友Id(\"経路0\") の端点)"
    );
}

#[test]
fn 無向で辺idだけが利用者の宣言型なら端点の綴りだけを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.宣言キーの交友(
            利用者が宣言した経路キー("経路0"),
            診断::宣言キーの交友::new(生成キーの地点のキーを作る("ミオ"), 生成キーの地点のキーを作る("ミオ")),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキー 生成キーの地点Id(\"ミオ\") が 生成キーの地点 として見つかりません \
         (辺 `宣言キーの交友` の端点。辺のキーは表示できない)"
    );
}

#[test]
fn 無向で端点だけが利用者の宣言型なら辺の綴りだけを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの親交(
            診断::生成キーの親交Id("経路0".into()),
            診断::生成キーの親交::new(
                利用者が宣言した地点キー("ミオ"),
                利用者が宣言した地点キー("ミオ"),
            ),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキーが 宣言キーの地点 として見つかりません \
         (辺 `生成キーの親交` 生成キーの親交Id(\"経路0\") の端点。端点のキーは表示できない)"
    );
}

#[test]
fn 無向で端点も辺idも利用者の宣言型なら綴りを載せず省いた理由だけを添える() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.宣言キーの親交(
            利用者が宣言した経路キー("経路0"),
            診断::宣言キーの親交::new(
                利用者が宣言した地点キー("ミオ"),
                利用者が宣言した地点キー("ミオ"),
            ),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキーが 宣言キーの地点 として見つかりません \
         (辺 `宣言キーの親交` の端点。端点のキーと辺のキーは表示できない)"
    );
}
