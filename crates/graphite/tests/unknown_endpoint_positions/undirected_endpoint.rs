//! 無向辺が未知の端点キーを参照したときの診断文を、4通りの組み合わせで固定する。
//!
//! 無向辺の両端は位置の区別を持たないため、どちらの端点が報告されるかを試験が
//! 決めないよう、両端に同じ未知のキーを置いた自己ループで確かめる。

use crate::{
    構築に失敗させる, 生成キーの地点のキー, 利用者が宣言した地点キー, 利用者が宣言した経路キー,
    診断,
};

#[test]
fn 無向の端点も辺idも生成id型なら両方の綴りを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの交友(
            診断::生成キーの交友Id("経路0".into()),
            診断::生成キーの交友::new(生成キーの地点のキー("ミオ"), 生成キーの地点のキー("ミオ")),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキー 生成キーの地点Id(\"ミオ\") が 生成キーの地点 として見つかりません \
         (辺 `生成キーの交友` 生成キーの交友Id(\"経路0\") の端点)"
    );
}

#[test]
fn 無向で辺idだけが利用者の宣言型なら端点の綴りだけを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.宣言キーの交友(
            利用者が宣言した経路キー("経路0"),
            診断::宣言キーの交友::new(生成キーの地点のキー("ミオ"), 生成キーの地点のキー("ミオ")),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキー 生成キーの地点Id(\"ミオ\") が 生成キーの地点 として見つかりません \
         (辺 `宣言キーの交友` の端点。辺のキーは利用者が宣言したID型のため表示しない)"
    );
}

#[test]
fn 無向で端点だけが利用者の宣言型なら辺の綴りだけを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの親交(
            診断::生成キーの親交Id("経路0".into()),
            診断::生成キーの親交::new(
                利用者が宣言した地点キー("ミオ"),
                利用者が宣言した地点キー("ミオ"),
            ),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキーが 宣言キーの地点 として見つかりません \
         (辺 `生成キーの親交` 生成キーの親交Id(\"経路0\") の端点。端点のキーは利用者が宣言したID型のため表示しない)"
    );
}

#[test]
fn 無向で端点も辺idも利用者の宣言型なら綴りを載せず省いた理由だけを添える() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.宣言キーの親交(
            利用者が宣言した経路キー("経路0"),
            診断::宣言キーの親交::new(
                利用者が宣言した地点キー("ミオ"),
                利用者が宣言した地点キー("ミオ"),
            ),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキーが 宣言キーの地点 として見つかりません \
         (辺 `宣言キーの親交` の端点。端点のキーと辺のキーは利用者が宣言したID型のため表示しない)"
    );
}
