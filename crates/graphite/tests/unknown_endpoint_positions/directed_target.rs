//! 有向辺が未知の終点キーを参照したときの診断文を、4通りの組み合わせで固定する。

use crate::{
    構築に失敗させる, 生成キーの地点, 生成キーの地点のキー, 利用者が宣言した地点キー,
    利用者が宣言した経路キー, 宣言キーの地点, 診断,
};

#[test]
fn 終点でも端点と辺idが生成id型なら両方の綴りを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの地点(生成キーの地点のキー("出発元"), 生成キーの地点);
        builder.生成キーの経路(
            診断::生成キーの経路Id("経路0".into()),
            診断::生成キーの経路::new(生成キーの地点のキー("出発元"), 生成キーの地点のキー("ミオ")),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキー 生成キーの地点Id(\"ミオ\") が 生成キーの地点 として見つかりません \
         (辺 `生成キーの経路` 生成キーの経路Id(\"経路0\") の終点)"
    );
}

#[test]
fn 終点で辺idだけが利用者の宣言型なら端点の綴りだけを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの地点(生成キーの地点のキー("出発元"), 生成キーの地点);
        builder.宣言キーの経路(
            利用者が宣言した経路キー("経路0"),
            診断::宣言キーの経路::new(生成キーの地点のキー("出発元"), 生成キーの地点のキー("ミオ")),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキー 生成キーの地点Id(\"ミオ\") が 生成キーの地点 として見つかりません \
         (辺 `宣言キーの経路` の終点。辺のキーは利用者が宣言したID型のため表示しない)"
    );
}

#[test]
fn 終点で端点だけが利用者の宣言型なら辺の綴りだけを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.宣言キーの地点(利用者が宣言した地点キー("出発元"), 宣言キーの地点);
        builder.生成キーの連絡(
            診断::生成キーの連絡Id("経路0".into()),
            診断::生成キーの連絡::new(
                利用者が宣言した地点キー("出発元"),
                利用者が宣言した地点キー("ミオ"),
            ),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキーが 宣言キーの地点 として見つかりません \
         (辺 `生成キーの連絡` 生成キーの連絡Id(\"経路0\") の終点。端点のキーは利用者が宣言したID型のため表示しない)"
    );
}

#[test]
fn 終点で端点も辺idも利用者の宣言型なら綴りを載せず省いた理由だけを添える() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.宣言キーの地点(利用者が宣言した地点キー("出発元"), 宣言キーの地点);
        builder.宣言キーの連絡(
            利用者が宣言した経路キー("経路0"),
            診断::宣言キーの連絡::new(
                利用者が宣言した地点キー("出発元"),
                利用者が宣言した地点キー("ミオ"),
            ),
        );
    });
    assert_eq!(
        違反.to_string(),
        "未知のキーが 宣言キーの地点 として見つかりません \
         (辺 `宣言キーの連絡` の終点。端点のキーと辺のキーは利用者が宣言したID型のため表示しない)"
    );
}
