//! このファイルは、`unique pair` の端点対が重複したときの診断文を固定する。
//!
//! この違反は端点対だけを載せるため、辺のキーではなく端点のID型の組み合わせで
//! 分かれる。有向辺は始点と終点のID型で4通り、無向辺は両端が同型のため2通りある。

use crate::{
    構築に失敗させる, 生成キーの地点, 生成キーの地点のキーを作る, 利用者が宣言した地点キー,
    宣言キーの地点, 診断,
};

#[test]
fn 始点も終点も生成id型なら両方の綴りを載せる() {
    let 違反 = 構築に失敗させる(|builder| {
        builder.生成キーの地点(生成キーの地点のキーを作る("甲"), 生成キーの地点);
        builder.生成キーの地点(生成キーの地点のキーを作る("乙"), 生成キーの地点);
        for 連番 in 0..2 {
            builder.両端が生成キーの専有経路(
                診断::両端が生成キーの専有経路Id(format!("経路{連番}")),
                診断::両端が生成キーの専有経路::new(
                    生成キーの地点のキーを作る("甲"),
                    生成キーの地点のキーを作る("乙"),
                ),
            );
        }
    });
    assert_eq!(
        違反.to_string(),
        "unique pair違反: 辺 `両端が生成キーの専有経路` は \
         生成キーの地点Id(\"甲\") -> 生成キーの地点Id(\"乙\") の対に既に辺が存在します"
    );
}

