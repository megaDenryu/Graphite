// `Nodes`/`Edges`/`NodeRefs`/`EdgeRefs` が持つ、個体・具体辺1件ごとの
// フィールドの追跡情報 (issue #41 §5.3「Nodesのフィールド、NodeRefs・
// EdgeRefsのフィールド」)。フィールド名自体は個体名・辺名をそのまま写した
// ものであり `naming::type_names` のように新しい識別子を作らないため、
// ここでは `追跡情報` だけを返す (`static_graph::naming::card_names` と
// 同じ形)。

use crate::schema::codegen::宣言元ファイルの綴り;
use crate::static_graph::semantic::{具体辺, 個体, 意味モデル};
use crate::static_graph::trace::{名前の由来, 意味項目, 追跡情報, 追跡情報構築器};

pub(crate) fn nodesフィールドの追跡情報を作る(
    意味モデル: &意味モデル,
    個体: &個体,
    宣言元: &宣言元ファイルの綴り,
) -> 追跡情報 {
    追跡情報構築器::new(
        名前の由来::InstanceNode { 個体名: 個体.名前().clone() },
        "Graphite 静的グラフの個体実体フィールド。`Nodes` がこの個体の実体を所有する。",
    )
    .意味項目を足す(意味項目::new("graph", 意味モデル.グラフ名()))
    .意味項目を足す(意味項目::new("個体", 個体.名前()))
    .意味項目を足す(意味項目::new("実体型", 個体.実体型()))
    .宣言を添える(宣言元, 個体.宣言の形())
    .完成する()
}

pub(crate) fn edgesフィールドの追跡情報を作る(
    意味モデル: &意味モデル,
    具体辺: &具体辺,
    宣言元: &宣言元ファイルの綴り,
) -> 追跡情報 {
    追跡情報構築器::new(
        名前の由来::InstanceEdge { 辺名: 具体辺.名前().clone() },
        "Graphite 静的グラフの辺実体フィールド。`Edges` がこの具体辺の実体を所有する。",
    )
    .意味項目を足す(意味項目::new("graph", 意味モデル.グラフ名()))
    .意味項目を足す(意味項目::new("具体辺", 具体辺.名前()))
    .意味項目を足す(意味項目::new("辺種別", 具体辺.種別().名前()))
    .宣言を添える(宣言元, 具体辺.宣言の形())
    .完成する()
}

