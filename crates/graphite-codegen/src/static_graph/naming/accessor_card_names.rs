// `NodeRefs`/`EdgeRefs` が持つ、個体・具体辺1件ごとの読み出しメソッドの
// 追跡情報 (issue #41 §5.3「NodeRefs・EdgeRefsのアクセサメソッド」)。
// メソッド名自体は個体名・辺名をそのまま写したものであり
// `naming::type_names` のように新しい識別子を作らないため、ここでは
// `追跡情報` だけを返す (`static_graph::naming::card_names` と同じ形)。
//
// `Nodes`/`Edges` 自身が持つ個体実体・辺実体フィールドは非公開であり
// (値ありの個体・積み荷を構築子から差し替えられる穴を塞ぐため)、docを
// 持たないのでこのファイルの対象から外れる。

use crate::static_graph::declaration_sites::宣言元の対;
use crate::static_graph::semantic::{具体辺, 個体, 意味モデル};
use crate::static_graph::trace::{名前の由来, 意味項目, 追跡情報, 追跡情報構築器};

// このファイルの2関数はどちらもinstance自身の宣言 (`node`/`edge`) だけを
// 参照するため、`宣言元の対` のうち `.instance()` だけを読む。

pub(crate) fn node_refsメソッドの追跡情報を作る(
    意味モデル: &意味モデル,
    個体: &個体,
    宣言元: &宣言元の対,
) -> 追跡情報 {
    追跡情報構築器::new(
        名前の由来::InstanceNode { 個体名: 個体.名前().clone() },
        "Graphite 静的グラフの個体参照メソッド。`NodeRefs` がこのメソッドでこの個体の具体参照を返す。",
    )
    .意味項目を足す(意味項目::new("graph", 意味モデル.グラフ名()))
    .意味項目を足す(意味項目::new("個体", 個体.名前()))
    .宣言を添える(宣言元.instance(), 個体.宣言の形())
    .完成する()
}

pub(crate) fn edge_refsメソッドの追跡情報を作る(
    意味モデル: &意味モデル,
    具体辺: &具体辺,
    宣言元: &宣言元の対,
) -> 追跡情報 {
    追跡情報構築器::new(
        名前の由来::InstanceEdge { 辺名: 具体辺.名前().clone() },
        "Graphite 静的グラフの辺参照メソッド。`EdgeRefs` がこのメソッドでこの具体辺の具体参照を返す。",
    )
    .意味項目を足す(意味項目::new("graph", 意味モデル.グラフ名()))
    .意味項目を足す(意味項目::new("具体辺", 具体辺.名前()))
    .宣言を添える(宣言元.instance(), 具体辺.宣言の形())
    .完成する()
}
