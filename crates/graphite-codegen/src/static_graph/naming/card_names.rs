// 意味カードだけに使う追跡情報の組み立て (issue #41 §5.2)。ここが返す名前
// は既にinstanceの宣言をそのまま写しただけの識別子 (辺アクセサメソッド名は
// `具体辺.名前()` そのもの) なので `format_ident!` は使わない。
// `static_graph::file::instance_file` (edge_ref・node_ref) が doc属性へ
// 変換して生成ファイルへ出す。`Nodes::new`/`Edges::new` の意味カードは
// 別の関心事 (`construction_card_names`) へ分けてある。

use proc_macro2::Ident;

use crate::static_graph::declaration_sites::宣言元の対;
use crate::static_graph::schema::input::積み荷宣言;
use crate::static_graph::semantic::{個体, 具体辺, 意味モデル};
use crate::static_graph::trace::{名前の由来, 意味項目, 追跡情報, 追跡情報構築器};

const 検証制約の補足: &str =
    "instance の辺の集合が満たすことを展開時に検査済み。戻り値の型は制約ではなく具体辺の宣言が決める";

// `{個体名}Ref` の `{辺名}()` (辺アクセサメソッド) の追跡情報。メソッド名
// 自体は `具体辺.名前()` のechoであり、ここでは意味カードだけを作る。
pub(crate) fn 辺アクセサメソッドの追跡情報を作る(
    意味モデル: &意味モデル,
    個体: &個体,
    具体辺: &具体辺,
    宣言元: &宣言元の対,
) -> 追跡情報 {
    // 自己ループ辺 (始点と終点が同じ個体) では個体が両方の役割を同時に持つ
    // ため、役割一覧は複数件になり得る (`・` で連ねて両方を示す)。
    let 役割列 = 具体辺.個体の役割一覧(個体.名前());
    assert!(!役割列.is_empty(), "端点として呼ばれるので役割を1つ以上持つ");
    // 単一役割のときは従来と同じ「`役割名`」の1件になり、自己ループ辺の
    // 2件は「`役割名1`・`役割名2`」になる (`意味項目::new` と同じ
    // バッククォート書式を役割ごとに保つ)。
    let 役割表示 = 役割列.iter().map(|役割| format!("`{役割}`")).collect::<Vec<_>>().join("・");
    追跡情報構築器::new(
        名前の由来::InstanceEdge { 辺名: 具体辺.名前().clone() },
        "Graphite 静的グラフの具体辺参照を返す。",
    )
    .意味項目を足す(意味項目::new("graph", 意味モデル.グラフ名()))
    .意味項目を足す(意味項目::new("個体", 個体.名前()))
    .意味項目を足す(意味項目::new("具体辺", 具体辺.名前()))
    .意味項目を足す(意味項目::new("辺種別", 具体辺.種別().名前()))
    .意味項目を足す(意味項目::組み立て済みの値で("この個体の役割", &役割表示))
    .意味項目を足す(意味項目::new("戻り値", format!("{}Ref", 具体辺.名前())))
    .宣言を添える(宣言元.instance(), 具体辺.宣言の形())
    .関係schema宣言を添える(宣言元.schema(), 具体辺.種別().宣言の形())
    .完成する()
}

// `{辺名}Ref` の役割アクセサ (`.member()` / `.team()` 等) の追跡情報。役割は
// 呼び出し元 (`file::instance_file::edge_ref` の `一アクセサを組み立てる`)
// が既に区別して持っているものをそのまま受け取る。ここで個体名から
// 「最初に一致した役割」を引き直すと、自己ループ辺 (始点と終点が同じ個体)
// の第二アクセサが第一役割と誤表示される。
pub(crate) fn 役割アクセサの追跡情報を作る(
    具体辺: &具体辺,
    役割: &Ident,
    具体端点: &個体,
    宣言元: &宣言元の対,
) -> 追跡情報 {
    let mut 構築器 = 追跡情報構築器::new(
        名前の由来::SchemaRole { 種別名: 具体辺.種別().名前().clone(), 役割: 役割.clone() },
        "Graphite 静的グラフの端点の役割アクセサ。",
    )
    .意味項目を足す(意味項目::new("辺種別", 具体辺.種別().名前()))
    .意味項目を足す(意味項目::new("役割", format!("{役割}: {}", 具体端点.実体型())))
    .意味項目を足す(意味項目::new("具体辺", 具体辺.名前()))
    .意味項目を足す(意味項目::new("具体端点", 具体端点.名前()))
    .意味項目を足す(意味項目::new("戻り値", format!("{}Ref", 具体端点.名前())));
    if let Some(制約文) = 具体辺.種別().制約列を表示する() {
        構築器 = 構築器.意味項目を足す(意味項目::補足付き("検証制約", 制約文, 検証制約の補足));
    }
    構築器
        .宣言を添える(宣言元.schema(), 具体辺.種別().宣言の形())
        .関係instance宣言を添える(宣言元.instance(), 具体辺.宣言の形())
        .完成する()
}

// `{辺名}Ref` の積み荷アクセサ (`.任命()` 等) の追跡情報。積み荷を持たない
// 種別の具体辺には呼ばない (呼び出し側が `辺.種別().積み荷()` で事前に絞る)。
pub(crate) fn 積み荷アクセサの追跡情報を作る(具体辺: &具体辺, 宣言元: &宣言元の対) -> 追跡情報 {
    let 積み荷宣言 { 役割, 型 } = 具体辺.種別().積み荷().expect("積み荷ありの具体辺だけを渡す");
    追跡情報構築器::new(
        名前の由来::SchemaPayloadRole { 種別名: 具体辺.種別().名前().clone(), 積み荷役割: 役割.clone() },
        "Graphite 静的グラフの積み荷アクセサ。",
    )
    .意味項目を足す(意味項目::new("辺種別", 具体辺.種別().名前()))
    .意味項目を足す(意味項目::new("積み荷", format!("{役割}: {型}")))
    .意味項目を足す(意味項目::new("具体辺", 具体辺.名前()))
    .宣言を添える(宣言元.schema(), 具体辺.種別().宣言の形())
    .関係instance宣言を添える(宣言元.instance(), 具体辺.宣言の形())
    .完成する()
}
