// instanceの辺1本ごとの検証: 種別がschemaに実在するか、向き (有向/無向) が
// 一致するか、積み荷の有無が一致するか、端点の実体型が役割の要求する型と
// 一致するか。

use proc_macro2::Ident;

use crate::static_graph::literal::input::{辺形状 as 具体形状, 辺中身, 辺宣言 as 具体辺宣言, 静的グラフ入力};
use crate::static_graph::schema::input::{辺形状 as 型形状, 静的グラフ型入力};

pub(super) fn 辺を検証する(schema: &静的グラフ型入力, instance: &静的グラフ入力, 辺: &具体辺宣言) -> syn::Result<()> {
    let 型宣言 = schema.辺宣言を種別名で探す(&辺.種別).ok_or_else(|| {
        syn::Error::new_spanned(&辺.種別, format!("`{}` はschemaに無い種別です", 辺.種別))
    })?;

    match (&型宣言.形状, &辺.形状) {
        (型形状::有向 { 始点型, 終点型, .. }, 具体形状::有向 { 始点, 終点, 中身 }) => {
            端点型を検証する(instance, 始点, 始点型)?;
            端点型を検証する(instance, 終点, 終点型)?;
            積み荷有無を検証する(辺, 型宣言.形状.積み荷().is_some(), 中身)?;
        }
        (型形状::無向 { 第1型, 第2型, .. }, 具体形状::無向 { 端点1, 端点2, 中身 }) => {
            端点型を検証する(instance, 端点1, 第1型)?;
            端点型を検証する(instance, 端点2, 第2型)?;
            積み荷有無を検証する(辺, 型宣言.形状.積み荷().is_some(), 中身)?;
        }
        (型形状::有向 { .. }, 具体形状::無向 { .. }) => {
            return Err(syn::Error::new_spanned(
                &辺.名前,
                format!("向きの不一致: 種別 `{}` は有向 (`->`) ですが、辺 `{}` は無向 (`--`) で書かれています", 辺.種別, 辺.名前),
            ));
        }
        (型形状::無向 { .. }, 具体形状::有向 { .. }) => {
            return Err(syn::Error::new_spanned(
                &辺.名前,
                format!("向きの不一致: 種別 `{}` は無向 (`--`) ですが、辺 `{}` は有向で書かれています", 辺.種別, 辺.名前),
            ));
        }
    }
    Ok(())
}

fn 端点型を検証する(instance: &静的グラフ入力, 個体: &Ident, 期待型: &Ident) -> syn::Result<()> {
    let 実体型 = instance.個体の実体型(個体);
    if 実体型 != 期待型 {
        return Err(syn::Error::new_spanned(
            個体,
            format!("端点の実体型の不一致: `{}` の実体型は `{}` ですが、この役割は `{}` 型を要求します", 個体, 実体型, 期待型),
        ));
    }
    Ok(())
}

fn 積み荷有無を検証する(辺: &具体辺宣言, 種別は積み荷を持つか: bool, 中身: &辺中身) -> syn::Result<()> {
    match (種別は積み荷を持つか, 中身) {
        (true, 辺中身::無積み荷) => Err(syn::Error::new_spanned(
            &辺.名前,
            format!("積み荷の有無の不一致: 種別 `{}` は積み荷が必要ですが、辺 `{}` に積み荷がありません", 辺.種別, 辺.名前),
        )),
        (false, 辺中身::積み荷あり(_)) => Err(syn::Error::new_spanned(
            &辺.名前,
            format!("積み荷の有無の不一致: 種別 `{}` は積み荷を持てませんが、辺 `{}` に積み荷が書かれています", 辺.種別, 辺.名前),
        )),
        _ => Ok(()),
    }
}
