//! 生成する違反列挙型が持つ違反の種類と、その並びを確定して持つ。

use proc_macro2::Ident;

use super::cardinality::EachSide;
use super::edge_definition::{辺定義, 辺定義番号};
use super::node_definition::ノード定義番号;

/// 凍結時に検出しうる違反1種類。生成物では列挙型の variant 1つになる。
pub enum 違反定義 {
    ノードのキーが重複した {
        ノード: ノード定義番号,
    },
    辺のキーが重複した {
        辺: 辺定義番号,
    },
    未知の始点を参照した {
        辺: 辺定義番号,
    },
    未知の終点を参照した {
        辺: 辺定義番号,
    },
    未知の端点を参照した {
        辺: 辺定義番号,
    },
    多重度に反した {
        辺: 辺定義番号,
        側: EachSide,
        役割名: Ident,
    },
    端点対が重複した {
        辺: 辺定義番号,
    },
}

/// スキーマ1つ分の違反定義を、生成する順に並べたもの。
///
/// 注意: 並びは生成物の variant 順そのものである。全ノードのキー重複を先に置き、
/// 続けて辺ごとに [キー重複, 未知の始点, 未知の終点, 多重度 (`where` 節の記述順),
/// 端点対の重複] を並べる。並べ替えると生成物が変わる。
pub struct 違反定義の目録 {
    違反定義の列: Vec<違反定義>,
}

impl 違反定義の目録 {
    pub(super) fn 定義の列から組み立てる(
        ノードの件数: usize,
        辺定義の列: &[辺定義],
    ) -> Self {
        let mut 違反定義の列: Vec<違反定義> = (0..ノードの件数)
            .map(|添字| 違反定義::ノードのキーが重複した {
                ノード: ノード定義番号::添字から作る(添字),
            })
            .collect();
        for (添字, 辺) in 辺定義の列.iter().enumerate() {
            let 辺番号 = 辺定義番号::添字から作る(添字);
            違反定義の列.push(違反定義::辺のキーが重複した { 辺: 辺番号 });
            if 辺.有向か() {
                違反定義の列.push(違反定義::未知の始点を参照した { 辺: 辺番号 });
                違反定義の列.push(違反定義::未知の終点を参照した { 辺: 辺番号 });
                for 制約 in 辺.記述順の役割の多重度制約() {
                    違反定義の列.push(違反定義::多重度に反した {
                        辺: 辺番号,
                        側: 制約.側(),
                        役割名: 制約.役割名().clone(),
                    });
                }
            } else {
                違反定義の列.push(違反定義::未知の端点を参照した { 辺: 辺番号 });
            }
            if 辺.端点対の重複可否().対ごとに1本だけか() {
                違反定義の列.push(違反定義::端点対が重複した { 辺: 辺番号 });
            }
        }
        Self { 違反定義の列 }
    }

    pub fn 違反定義の列(&self) -> &[違反定義] {
        &self.違反定義の列
    }
}
