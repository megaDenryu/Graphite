//! 完成した `Graph` を複製できるかという、schema 全体に属する選択を表す。
//!
//! 既定は複製できない。複製できる schema は、生成される `Graph` と
//! 凍結済みの辺レコードへ `Clone` を導出するため、利用者のノード値型と
//! 積み荷の型に `Clone` を要求する (`docs/schema_v4.md` §3.1.3)。既定で
//! 要求しないのは、Graphite 自身の意味論が複製を必要としないためである
//! (同 §3.1.2)。

// 利用者が schema 宣言の前に `#[derive(Clone)]` を書いたかどうかで決まる。
pub enum 完成したグラフの複製可否 {
    複製できる,
    複製できない,
}
