//! ノード参照へ生やす探索操作の並びを、生成する順のまま確定して持つ。
//!
//! このファイルは1ファイル100行の原則の例外である (区分: 統合による超過)。
//! ノード参照へ生やす探索操作の並びを、生成する順のまま1つの表として持つ。本体
//! は64行で、残りは同居する単体テストである。超過を許す根拠の台帳は
//! `docs/development/line_count_ledger.md` にある。

use proc_macro2::Ident;

use super::cardinality::{EachSide, RoleCardinality};
use super::edge_definition::{辺の向き, 辺定義, 辺定義番号};
use super::node_definition::ノード定義番号;

// あるノードから辺を辿る操作1つ分。`役割による探索` は有向辺の
// `{kind}_as_{役割}()` を、`接続による探索` は無向辺の `{kind}_incident()` を、
// `端点対による探索` は `{kind}_between()` と `{kind}_try_between()` を生む。
pub enum 探索操作 {
    役割による探索 {
        辺: 辺定義番号,
        役割名: Ident,
        側: EachSide,
        多重度: RoleCardinality,
    },
    接続による探索 {
        辺: 辺定義番号,
    },
    端点対による探索 {
        辺: 辺定義番号,
    },
}

// ノード種別1つ分の探索操作の並び。
//
// 注意: 並びは生成物の順序そのものである。外側は辺の宣言順、1つの辺の中では
// 始点役割・終点役割・端点対の順に並ぶ。ノード単位に集め直して辺を跨いで
// 並べ替えると生成物が変わる。
pub struct ノードの探索計画 {
    操作の列: Vec<探索操作>,
}

impl ノードの探索計画 {
    pub(super) fn ノードと辺定義から組み立てる(
        ノード: ノード定義番号,
        辺定義の列: &[辺定義],
    ) -> Self {
        let mut 操作の列 = Vec::new();
        for (添字, 辺) in 辺定義の列.iter().enumerate() {
            let 辺番号 = 辺定義番号::添字から作る(添字);
            match 辺.向き() {
                辺の向き::有向 { 始点, 終点 } => {
                    if 始点.ノード() == ノード {
                        操作の列.push(探索操作::役割による探索 {
                            辺: 辺番号,
                            役割名: 始点.役割名().clone(),
                            側: EachSide::Source,
                            多重度: 辺.側の多重度(EachSide::Source),
                        });
                    }
                    if 終点.ノード() == ノード {
                        操作の列.push(探索操作::役割による探索 {
                            辺: 辺番号,
                            役割名: 終点.役割名().clone(),
                            側: EachSide::Target,
                            多重度: 辺.側の多重度(EachSide::Target),
                        });
                    }
                }
                辺の向き::無向 { 端点のノード } => {
                    if *端点のノード == ノード {
                        操作の列.push(探索操作::接続による探索 { 辺: 辺番号 });
                    }
                }
            }
            // 端点対検索は位置0側 (有向辺の始点、無向辺の唯一の端点型) の
            // ノードにだけ生やす。両端が同じノード型でも1回しか生えない。
            if 辺.始点のノード定義番号() == ノード {
                操作の列.push(探索操作::端点対による探索 { 辺: 辺番号 });
            }
        }
        Self { 操作の列 }
    }

    pub fn 操作の列(&self) -> &[探索操作] {
        &self.操作の列
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::semantic::analyze::検査用にdslからスキーマ定義を組み立てる;

    // 探索操作を「種類と辺の添字」の並びへ落とし、順序だけを比べられるようにする。
    fn 操作の並び(計画: &ノードの探索計画) -> Vec<(&'static str, usize)> {
        計画
            .操作の列()
            .iter()
            .map(|操作| match 操作 {
                探索操作::役割による探索 { 辺, 側, .. } => match 側 {
                    EachSide::Source => ("始点役割", 辺.添字()),
                    EachSide::Target => ("終点役割", 辺.添字()),
                },
                探索操作::接続による探索 { 辺 } => ("接続", 辺.添字()),
                探索操作::端点対による探索 { 辺 } => ("端点対", 辺.添字()),
            })
            .collect()
    }

    #[test]
    fn 探索操作は辺の宣言順に始点役割_終点役割_端点対の順で並ぶ() {
        let 定義 = 検査用にdslからスキーマ定義を組み立てる(
            "schema Org {
                node Person;
                edge Boss = (subordinate: Person) -> (superior: Person);
                edge Friends = Person -- Person;
            }",
        );
        assert_eq!(
            操作の並び(&定義.ノードごとの探索計画()[0]),
            vec![
                ("始点役割", 0),
                ("終点役割", 0),
                ("端点対", 0),
                ("接続", 1),
                ("端点対", 1),
            ],
            "外側は辺の宣言順、1つの辺の中では始点役割・終点役割・端点対の順"
        );
    }

    #[test]
    fn 端点対の探索は位置0側のノードにだけ生える() {
        let 定義 = 検査用にdslからスキーマ定義を組み立てる(
            "schema Org {
                node Person;
                node Team;
                edge Belongs = (member: Person) -> (team: Team);
            }",
        );
        assert_eq!(
            操作の並び(&定義.ノードごとの探索計画()[0]),
            vec![("始点役割", 0), ("端点対", 0)]
        );
        assert_eq!(
            操作の並び(&定義.ノードごとの探索計画()[1]),
            vec![("終点役割", 0)],
            "終点側のノードには端点対の探索を生やさない"
        );
    }
}
