use std::marker::PhantomData;

use super::台帳モジュール::台帳;
use super::ノード参照モジュール::ノード参照;
use super::ノードタグモジュール::ノードタグ;
use super::無向辺モジュール::無向辺;

// 無向辺参照の形。端点1()/端点2() は無向辺の実体の端点からノード参照を
// 組み立てて返す (向きに意味を持たせないため始点/終点ではなく番号で呼ぶ)。
pub struct 無向辺参照<'a, ノード達型, 辺達型, 種別, 端点1タグ: ノードタグ, 端点2タグ: ノードタグ, 積み荷 = ()> {
    pub 実体: &'a 無向辺<'a, 種別, 端点1タグ::実体, 端点2タグ::実体, 積み荷>,
    pub 台帳: 台帳<'a, ノード達型, 辺達型>,
    _印: PhantomData<(端点1タグ, 端点2タグ)>,
}
impl<'a, ノード達型, 辺達型, 種別, 端点1タグ: ノードタグ, 端点2タグ: ノードタグ, 積み荷>
    無向辺参照<'a, ノード達型, 辺達型, 種別, 端点1タグ, 端点2タグ, 積み荷>
{
    pub fn new(
        実体: &'a 無向辺<'a, 種別, 端点1タグ::実体, 端点2タグ::実体, 積み荷>,
        台帳: 台帳<'a, ノード達型, 辺達型>,
    ) -> Self {
        Self { 実体, 台帳, _印: PhantomData }
    }
    pub fn 端点1(&self) -> ノード参照<'a, ノード達型, 辺達型, 端点1タグ> { ノード参照::new(self.実体.端点1, self.台帳) }
    pub fn 端点2(&self) -> ノード参照<'a, ノード達型, 辺達型, 端点2タグ> { ノード参照::new(self.実体.端点2, self.台帳) }
    pub fn 積み荷(&self) -> &'a 積み荷 { &self.実体.積み荷 }
}
impl<'a, ノード達型, 辺達型, 種別, 端点1タグ: ノードタグ, 端点2タグ: ノードタグ, 積み荷> Clone
    for 無向辺参照<'a, ノード達型, 辺達型, 種別, 端点1タグ, 端点2タグ, 積み荷>
{
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型, 種別, 端点1タグ: ノードタグ, 端点2タグ: ノードタグ, 積み荷> Copy
    for 無向辺参照<'a, ノード達型, 辺達型, 種別, 端点1タグ, 端点2タグ, 積み荷>
{
}
