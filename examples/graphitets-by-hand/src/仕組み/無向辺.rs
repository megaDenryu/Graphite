use std::marker::PhantomData;

// 無向辺の実体。端点は「始点/終点」ではなく対称な2端点として持つ。積み荷は
// 辺と同じく所有値で、無しの場合は () とする (issue #24 段階2)。
pub struct 無向辺<'a, 種別, 端点1, 端点2, 積み荷 = ()> {
    pub 端点1: &'a 端点1,
    pub 端点2: &'a 端点2,
    pub 積み荷: 積み荷,
    pub _種別: PhantomData<種別>,
}

// 無向に結ぶ(友人, &n.太郎, &n.次郎) は積み荷なしで対称な辺を構築する。
pub fn 無向に結ぶ<'a, 種別, 端点1, 端点2>(
    _種別: 種別,
    端点1: &'a 端点1,
    端点2: &'a 端点2,
) -> 無向辺<'a, 種別, 端点1, 端点2> {
    無向辺 { 端点1, 端点2, 積み荷: (), _種別: PhantomData }
}
