//! 仕組み (ドメインを知らない汎用層)。生成物1種類1ファイルの方針で分割する
//! (issue #24 段階2、積み荷付き辺・無向辺・種別契約・位置マーカーの追加で
//! 100行を超えたため)。役割は6つ。辺・無向辺=端点への参照と積み荷を持つ辺の
//! 実体。台帳=実体プール2つへの参照の束 (全参照が持ち歩く)。ノード参照=実体+
//! 台帳。辺参照・無向辺参照=実体+台帳+端点アクセサ。種別契約=種別ごとの積み荷
//! 型をレイヤー1からレイヤー2へ伝えるチャネル。個体ごとの違いは全部タグ
//! (ノードタグ) 1個に閉じ込め、この層はタグを跨いだ1本の形だけを持つ。
//! フィールド・メソッドは bin とマクロ生成コードから直接使うため pub にする
//! (詳細: `../bin/static_graph.rs` 冒頭コメント、issue #24)。
//!
//! 各 `mod` 宣言の識別子はファイル内の主要な生成物 (構造体・トレイト) と
//! 同名にせず `モジュール` を足す。同名にすると、その生成物を `pub use
//! X::*;` で再輸出したときに「private な mod 自身がその名前を占有し、公開
//! 再輸出を覆い隠す」(`hidden_glob_reexports`) ため、呼び出し側の `use
//! ...仕組み::*;` から生成物が一切見えなくなる (段階2で実測)。

