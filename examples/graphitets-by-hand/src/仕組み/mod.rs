//! 仕組み (ドメインを知らない汎用層)。生成物1種類1ファイルの方針で分割する。
//! 役割は4つ。辺=端点への参照を持つ辺の実体。台帳=実体プール2つへの参照の束
//! (全参照が持ち歩く)。ノード参照=実体+台帳。辺参照=実体+台帳+端点アクセサ。
//! 個体ごとの違いは全部タグ (ノードタグ) 1個に閉じ込め、この層はタグを跨いだ
//! 1本の形だけを持つ。フィールド・メソッドは bin から直接使うため pub にする
//! (詳細: `../bin/static_graph.rs` 冒頭コメント、issue #24)。
//!
//! マクロ版 (`静的グラフ型!`/`静的グラフ!`、issue #24 段階1〜2で確立) が
//! 生成するコードは、この仕組みへ依存しない全部具象のコードであるため、
//! ここは手書きの `static_graph.rs` だけが使う (issue #24 段階2で種別契約・
//! 位置マーカー・積み荷付き辺の型引数・無向辺・無向辺参照を削除)。マクロは
//! `graphite::static_schema!` として本体へ統合済みであり
//! (`examples/static-org` 参照)、この crate の `macros/` は削除した。
//!
//! 各 `mod` 宣言の識別子はファイル内の主要な生成物 (構造体・トレイト) と
//! 同名にせず `モジュール` を足す。同名にすると、その生成物を `pub use
//! X::*;` で再輸出したときに「private な mod 自身がその名前を占有し、公開
//! 再輸出を覆い隠す」(`hidden_glob_reexports`) ため、呼び出し側の `use
//! ...仕組み::*;` から生成物が一切見えなくなる (段階2で実測)。

