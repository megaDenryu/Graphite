use std::marker::PhantomData;

use super::台帳モジュール::台帳;
use super::ノード参照モジュール::ノード参照;
use super::ノードタグモジュール::ノードタグ;
use super::辺モジュール::辺;

// 辺参照の形。始点・終点の印を型引数に持ち、始点()/終点() は辺の実体の端点
// からノード参照を組み立てて返す (辺が辿りの根拠)。
pub struct 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> {
    pub 実体: &'a 辺<'a, 種別, 始点タグ::実体, 終点タグ::実体>,
    pub 台帳: 台帳<'a, ノード達型, 辺達型>,
    _印: PhantomData<(始点タグ, 終点タグ)>,
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ>
    辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ>
{
    pub fn new(
        実体: &'a 辺<'a, 種別, 始点タグ::実体, 終点タグ::実体>,
        台帳: 台帳<'a, ノード達型, 辺達型>,
    ) -> Self {
        Self { 実体, 台帳, _印: PhantomData }
    }
    pub fn 始点(&self) -> ノード参照<'a, ノード達型, 辺達型, 始点タグ> { ノード参照::new(self.実体.始点, self.台帳) }
    pub fn 終点(&self) -> ノード参照<'a, ノード達型, 辺達型, 終点タグ> { ノード参照::new(self.実体.終点, self.台帳) }
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> Clone
    for 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ>
{
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> Copy
    for 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ>
{
}
