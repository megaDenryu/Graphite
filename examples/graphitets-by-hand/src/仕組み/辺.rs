use std::marker::PhantomData;

// 辺の実体。端点の実体への参照と、辺1本ごとの積み荷 (所有値) を持つ。種別
// (恋人・友達 等) は実行時の中身を持たない純粋なラベルなので、そこだけ
// PhantomData で型に残す。積み荷なしの辺は 積み荷 = () として扱う
// (issue #24 段階2)。
pub struct 辺<'a, 種別, 始点, 終点, 積み荷 = ()> {
    pub 始点: &'a 始点,
    pub 終点: &'a 終点,
    pub 積み荷: 積み荷,
    pub _種別: PhantomData<種別>,
}

// 結ぶ(恋人, &n.太郎, &n.花子) と「種類・誰・誰」を全部名指しして構築する
// (積み荷なし)。
pub fn 結ぶ<'a, 種別, 始点, 終点>(_種別: 種別, 始点: &'a 始点, 終点: &'a 終点) -> 辺<'a, 種別, 始点, 終点> {
    辺 { 始点, 終点, 積み荷: (), _種別: PhantomData }
}

// 積んで結ぶ(上司, &n.太郎, &n.次郎, 任命記録 { .. }) は積み荷ありで構築する。
pub fn 積んで結ぶ<'a, 種別, 始点, 終点, 積み荷>(
    _種別: 種別,
    始点: &'a 始点,
    終点: &'a 終点,
    積み荷: 積み荷,
) -> 辺<'a, 種別, 始点, 終点, 積み荷> {
    辺 { 始点, 終点, 積み荷, _種別: PhantomData }
}
