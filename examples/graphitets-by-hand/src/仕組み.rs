// 仕組み (ドメインを知らない汎用層)。
//
// 役割は4つ。辺=端点への参照を持つ辺の実体。台帳=実体プール2つへの参照の束
// (全参照が持ち歩く)。ノード参照=実体+台帳。辺参照=実体+台帳+始点()/終点()。
// 個体ごとの違いは全部タグ (ノードタグ) 1個に閉じ込め、この層はタグを跨いだ
// 1本の形だけを持つ。フィールド・メソッドは bin とマクロ生成コードから直接
// 使うため pub にする (詳細: `../bin/static_graph.rs` 冒頭コメント、issue #24)。

use std::marker::PhantomData;

// 辺の実体。端点の実体への参照を持つ。種別 (恋人・友達 等) は実行時の中身を
// 持たない純粋なラベルなので、そこだけ PhantomData で型に残す。
pub struct 辺<'a, 種別, 始点, 終点> {
    pub 始点: &'a 始点,
    pub 終点: &'a 終点,
    pub _種別: PhantomData<種別>,
}

// 結ぶ(恋人, &n.太郎, &n.花子) と「種類・誰・誰」を全部名指しして構築する。
pub fn 結ぶ<'a, 種別, 始点, 終点>(_種別: 種別, 始点: &'a 始点, 終点: &'a 終点) -> 辺<'a, 種別, 始点, 終点> {
    辺 { 始点, 終点, _種別: PhantomData }
}

// 個体の印が「自分の実体は何型か」を知っているという契約。
pub trait ノードタグ {
    type 実体;
}

// 実体プール2つへの参照の束。全参照がこれを持ち歩く。
pub struct 台帳<'a, ノード達型, 辺達型> {
    pub ノード達: &'a ノード達型,
    pub 辺達: &'a 辺達型,
}
impl<'a, ノード達型, 辺達型> Clone for 台帳<'a, ノード達型, 辺達型> {
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型> Copy for 台帳<'a, ノード達型, 辺達型> {}

// ノード参照の形。個体ごとの違いは印 (タグ) だけで、形はこの1本で全員分。
pub struct ノード参照<'a, ノード達型, 辺達型, タグ: ノードタグ> {
    pub 実体: &'a タグ::実体,
    pub 台帳: 台帳<'a, ノード達型, 辺達型>,
    _印: PhantomData<タグ>,
}
impl<'a, ノード達型, 辺達型, タグ: ノードタグ> ノード参照<'a, ノード達型, 辺達型, タグ> {
    pub fn new(実体: &'a タグ::実体, 台帳: 台帳<'a, ノード達型, 辺達型>) -> Self {
        Self { 実体, 台帳, _印: PhantomData }
    }
}
impl<'a, ノード達型, 辺達型, タグ: ノードタグ> Clone for ノード参照<'a, ノード達型, 辺達型, タグ> {
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型, タグ: ノードタグ> Copy for ノード参照<'a, ノード達型, 辺達型, タグ> {}

// 辺参照の形。始点・終点の印を型引数に持ち、始点()/終点() は辺の実体の
// 端点からノード参照を組み立てて返す (辺が辿りの根拠)。
pub struct 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> {
    pub 実体: &'a 辺<'a, 種別, 始点タグ::実体, 終点タグ::実体>,
    pub 台帳: 台帳<'a, ノード達型, 辺達型>,
    _印: PhantomData<(始点タグ, 終点タグ)>,
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ> {
    pub fn new(実体: &'a 辺<'a, 種別, 始点タグ::実体, 終点タグ::実体>, 台帳: 台帳<'a, ノード達型, 辺達型>) -> Self {
        Self { 実体, 台帳, _印: PhantomData }
    }
    pub fn 始点(&self) -> ノード参照<'a, ノード達型, 辺達型, 始点タグ> { ノード参照::new(self.実体.始点, self.台帳) }
    pub fn 終点(&self) -> ノード参照<'a, ノード達型, 辺達型, 終点タグ> { ノード参照::new(self.実体.終点, self.台帳) }
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> Clone for 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ> {
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> Copy for 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ> {}
