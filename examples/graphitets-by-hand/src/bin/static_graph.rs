// 仕組みが lib クレートへ移った結果、人間関係ノード参照/人間関係辺参照は
// (型別名の中身としては) foreign な型になった。孤児規則 (E0116) により
// foreign な型へ直接 inherent impl は書けないため、ローカル trait を介して
// blanket impl する (issue #24 段階1で発見。lib 分割前は同一クレートだった
// ため inherent impl のままで通っていた)。

// 名前() は「実体が名前を持つ」ことだけを条件にした1つの trait + blanket impl
// で全個体分をまかなう。
trait 名前アクセス<'a> {
    fn 名前(&self) -> &'a str;
}
impl<'a, タグ: ノードタグ> 名前アクセス<'a> for 人間関係ノード参照<'a, タグ>
where
    タグ::実体: 名前持ち,
{
    fn 名前(&self) -> &'a str { self.実体.名前() }
}

// 恋人関係の辺参照は 男()/女()、友達関係の辺参照は 友達1()/友達2() で端点を返す。
// 種類ごとに1つの trait + blanket impl で、組が何組あっても足りる。
trait 恋人アクセス<'a> {
    type 男側: ノードタグ;
    type 女側: ノードタグ;
    fn 男(&self) -> 人間関係ノード参照<'a, Self::男側>;
    fn 女(&self) -> 人間関係ノード参照<'a, Self::女側>;
}
impl<'a, 男側タグ, 女側タグ> 恋人アクセス<'a> for 人間関係辺参照<'a, 恋人, 男側タグ, 女側タグ>
where
    男側タグ: ノードタグ<実体 = 男>,
    女側タグ: ノードタグ<実体 = 女>,
{
    type 男側 = 男側タグ;
    type 女側 = 女側タグ;
    fn 男(&self) -> 人間関係ノード参照<'a, 男側タグ> { self.始点() }
    fn 女(&self) -> 人間関係ノード参照<'a, 女側タグ> { self.終点() }
}
trait 友達アクセス<'a> {
    type 甲側: ノードタグ;
    type 乙側: ノードタグ;
    fn 友達1(&self) -> 人間関係ノード参照<'a, Self::甲側>;
    fn 友達2(&self) -> 人間関係ノード参照<'a, Self::乙側>;
}
impl<'a, 甲タグ: ノードタグ, 乙タグ: ノードタグ> 友達アクセス<'a> for 人間関係辺参照<'a, 友達, 甲タグ, 乙タグ> {
    type 甲側 = 甲タグ;
    type 乙側 = 乙タグ;
    fn 友達1(&self) -> 人間関係ノード参照<'a, 甲タグ> { self.始点() }
    fn 友達2(&self) -> 人間関係ノード参照<'a, 乙タグ> { self.終点() }
}

// どの個体がどの辺に繋がるかの人力解決。メソッド名が個体ごとに違うため、
// ここだけは個体ごとに書く (generics はメソッド名を生成できない)。
// 個体ごとに専用 trait を1つ立てて、その個体の型別名へ blanket ではなく
// 1対1で impl する (同じ trait を他個体が実装しないので曖昧さは出ない)。
trait 太郎の辺<'a> {
    fn 恋人の辺(&self) -> 太郎と花子参照<'a>;
    fn 次郎との友達の辺(&self) -> 太郎と次郎参照<'a>;
    fn 一郎との友達の辺(&self) -> 太郎と一郎参照<'a>;
}
impl<'a> 太郎の辺<'a> for 太郎参照<'a> {
    fn 恋人の辺(&self) -> 太郎と花子参照<'a> { 辺参照::new(&self.台帳.辺達.太郎と花子, self.台帳) }
    fn 次郎との友達の辺(&self) -> 太郎と次郎参照<'a> { 辺参照::new(&self.台帳.辺達.太郎と次郎, self.台帳) }
    fn 一郎との友達の辺(&self) -> 太郎と一郎参照<'a> { 辺参照::new(&self.台帳.辺達.太郎と一郎, self.台帳) }
}
trait 次郎の辺<'a> {
    fn 恋人の辺(&self) -> 次郎と桜参照<'a>;
    fn 太郎との友達の辺(&self) -> 太郎と次郎参照<'a>;
}
impl<'a> 次郎の辺<'a> for 次郎参照<'a> {
    fn 恋人の辺(&self) -> 次郎と桜参照<'a> { 辺参照::new(&self.台帳.辺達.次郎と桜, self.台帳) }
    fn 太郎との友達の辺(&self) -> 太郎と次郎参照<'a> { 辺参照::new(&self.台帳.辺達.太郎と次郎, self.台帳) }
}
trait 一郎の辺<'a> {
    fn 太郎との友達の辺(&self) -> 太郎と一郎参照<'a>;
}
impl<'a> 一郎の辺<'a> for 一郎参照<'a> {
    fn 太郎との友達の辺(&self) -> 太郎と一郎参照<'a> { 辺参照::new(&self.台帳.辺達.太郎と一郎, self.台帳) }
}
trait 花子の辺<'a> {
    fn 恋人の辺(&self) -> 太郎と花子参照<'a>;
    fn 桜との友達の辺(&self) -> 花子と桜参照<'a>;
    fn 恵子との友達の辺(&self) -> 花子と恵子参照<'a>;
}
impl<'a> 花子の辺<'a> for 花子参照<'a> {
    fn 恋人の辺(&self) -> 太郎と花子参照<'a> { 辺参照::new(&self.台帳.辺達.太郎と花子, self.台帳) }
    fn 桜との友達の辺(&self) -> 花子と桜参照<'a> { 辺参照::new(&self.台帳.辺達.花子と桜, self.台帳) }
    fn 恵子との友達の辺(&self) -> 花子と恵子参照<'a> { 辺参照::new(&self.台帳.辺達.花子と恵子, self.台帳) }
}
trait 桜の辺<'a> {
    fn 恋人の辺(&self) -> 次郎と桜参照<'a>;
    fn 花子との友達の辺(&self) -> 花子と桜参照<'a>;
}
impl<'a> 桜の辺<'a> for 桜参照<'a> {
    fn 恋人の辺(&self) -> 次郎と桜参照<'a> { 辺参照::new(&self.台帳.辺達.次郎と桜, self.台帳) }
    fn 花子との友達の辺(&self) -> 花子と桜参照<'a> { 辺参照::new(&self.台帳.辺達.花子と桜, self.台帳) }
}
