    fn 辿った先は宣言された実体と同一インスタンスである() {
        let ノード達 = ノード達::new();
        let 辺達 = 辺達::張る(&ノード達);
        let g = 人間関係グラフ::new(&ノード達, &辺達);
        assert!(std::ptr::eq(g.ノード参照達.太郎.恋人の辺().女().実体, &ノード達.花子));
        assert!(std::ptr::eq(g.辺参照達.太郎と花子.男().実体, g.ノード参照達.太郎.実体));
    }

    #[test]
    fn ノード参照が返す辺参照は辺参照達のものと同じ実体を指す() {
        let ノード達 = ノード達::new();
        let 辺達 = 辺達::張る(&ノード達);
        let g = 人間関係グラフ::new(&ノード達, &辺達);
        assert!(std::ptr::eq(
            g.ノード参照達.太郎.恋人の辺().実体,
            g.辺参照達.太郎と花子.実体
        ));
    }
