struct 辺達<'a> {
    太郎と花子: 恋人関係<'a>,
    次郎と桜: 恋人関係<'a>,
    太郎と次郎: 友達関係<'a, 男, 男>,
    太郎と一郎: 友達関係<'a, 男, 男>,
    花子と桜: 友達関係<'a, 女, 女>,
    花子と恵子: 友達関係<'a, 女, 女>,
}
impl<'a> 辺達<'a> {
    fn 張る(ノード達: &'a ノード達) -> Self {
        Self {
            太郎と花子: 結ぶ(恋人, &ノード達.太郎, &ノード達.花子),
            次郎と桜: 結ぶ(恋人, &ノード達.次郎, &ノード達.桜),
            太郎と次郎: 結ぶ(友達, &ノード達.太郎, &ノード達.次郎),
            太郎と一郎: 結ぶ(友達, &ノード達.太郎, &ノード達.一郎),
            花子と桜: 結ぶ(友達, &ノード達.花子, &ノード達.桜),
            花子と恵子: 結ぶ(友達, &ノード達.花子, &ノード達.恵子),
        }
    }
}

