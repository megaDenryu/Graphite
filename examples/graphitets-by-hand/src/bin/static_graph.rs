// 静的グラフ版。ノードの顔ぶれがコンパイル時に確定しているドメイングラフを、
// ID も HashMap も実行時検証も使わずに表す (main.rs の動的グラフ版との対比)。
//
// 役割は4つに分かれる:
//   実体の層   ノード達 = ノードの実体の唯一の所有者
//              辺達     = 辺の実体の唯一の所有者 (辺の実体は端点の実体を指す)
//   参照の層   ノード参照達・辺参照達 = 実体の層から作る。1参照 = 実体 + 台帳
//   グラフ     ノード参照達と辺参照達の2つを持つだけ
// 辿りは「ノード参照 → 自分が繋がる辺参照 → その辺が繋ぐノード参照」の往復で
// 何段でも進む。参照同士は互いを保持せず (保持すると相互参照で構築できない)、
// 台帳 (実体プール2つへの参照) を持ち歩いて相手の参照をその場で組み立てる。
//
// 仕組みと具体の境界: 参照の「形」(実体+台帳、始点/終点の辿り) は仕組みが持つ。
// 具体に残るのは「名前」だけ — 個体の印 (太郎)、型の別名 (太郎参照)、
// メソッド名 (恋人の辺)。Rust の generics は名前を生成できないため、
// この名前の量産だけが graph! マクロの領分として残る。
//
// 実行場所: C:\devs\Graphite\examples\graphitets-by-hand で
//   cargo run --bin static_graph
//   cargo test --bin static_graph

use std::marker::PhantomData;

// ---------------- 仕組み (ドメインを知らない汎用層) ----------------

// 辺の実体。端点の実体への参照を持つ。種別 (恋人・友達 等) は実行時の中身を
// 持たない純粋なラベルなので、そこだけ PhantomData で型に残す。
struct 辺<'a, 種別, 始点, 終点> {
    始点: &'a 始点,
    終点: &'a 終点,
    _種別: PhantomData<種別>,
}

// 結ぶ(恋人, &n.太郎, &n.花子) と「種類・誰・誰」を全部名指しして構築する。
fn 結ぶ<'a, 種別, 始点, 終点>(_種別: 種別, 始点: &'a 始点, 終点: &'a 終点) -> 辺<'a, 種別, 始点, 終点> {
    辺 { 始点, 終点, _種別: PhantomData }
}

// 個体の印が「自分の実体は何型か」を知っているという契約。
trait ノードタグ {
    type 実体;
}

// 実体プール2つへの参照の束。全参照がこれを持ち歩く。
struct 台帳<'a, ノード達型, 辺達型> {
    ノード達: &'a ノード達型,
    辺達: &'a 辺達型,
}
impl<'a, ノード達型, 辺達型> Clone for 台帳<'a, ノード達型, 辺達型> {
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型> Copy for 台帳<'a, ノード達型, 辺達型> {}

// ノード参照の形。個体ごとの違いは印 (タグ) だけで、形はこの1本で全員分。
struct ノード参照<'a, ノード達型, 辺達型, タグ: ノードタグ> {
    実体: &'a タグ::実体,
    台帳: 台帳<'a, ノード達型, 辺達型>,
    _印: PhantomData<タグ>,
}
impl<'a, ノード達型, 辺達型, タグ: ノードタグ> ノード参照<'a, ノード達型, 辺達型, タグ> {
    fn new(実体: &'a タグ::実体, 台帳: 台帳<'a, ノード達型, 辺達型>) -> Self {
        Self { 実体, 台帳, _印: PhantomData }
    }
}
impl<'a, ノード達型, 辺達型, タグ: ノードタグ> Clone for ノード参照<'a, ノード達型, 辺達型, タグ> {
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型, タグ: ノードタグ> Copy for ノード参照<'a, ノード達型, 辺達型, タグ> {}

// 辺参照の形。始点・終点の印を型引数に持ち、始点()/終点() は辺の実体の
// 端点からノード参照を組み立てて返す (辺が辿りの根拠)。
struct 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> {
    実体: &'a 辺<'a, 種別, 始点タグ::実体, 終点タグ::実体>,
    台帳: 台帳<'a, ノード達型, 辺達型>,
    _印: PhantomData<(始点タグ, 終点タグ)>,
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ> {
    fn new(実体: &'a 辺<'a, 種別, 始点タグ::実体, 終点タグ::実体>, 台帳: 台帳<'a, ノード達型, 辺達型>) -> Self {
        Self { 実体, 台帳, _印: PhantomData }
    }
    fn 始点(&self) -> ノード参照<'a, ノード達型, 辺達型, 始点タグ> { ノード参照::new(self.実体.始点, self.台帳) }
    fn 終点(&self) -> ノード参照<'a, ノード達型, 辺達型, 終点タグ> { ノード参照::new(self.実体.終点, self.台帳) }
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> Clone for 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ> {
    fn clone(&self) -> Self { *self }
}
impl<'a, ノード達型, 辺達型, 種別, 始点タグ: ノードタグ, 終点タグ: ノードタグ> Copy for 辺参照<'a, ノード達型, 辺達型, 種別, 始点タグ, 終点タグ> {}

