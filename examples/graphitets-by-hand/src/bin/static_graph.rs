// 静的グラフ版。ノードの顔ぶれがコンパイル時に確定しているドメイングラフを、
// ID も HashMap も実行時検証も使わずに表す (main.rs の動的グラフ版との対比)。
//
// 役割は4つに分かれる:
//   実体の層   ノード達 = ノードの実体の唯一の所有者
//              辺達     = 辺の実体の唯一の所有者 (辺の実体は端点の実体を指す)
//   参照の層   ノード参照達・辺参照達 = 実体の層から作る。1参照 = 実体 + 台帳
//   グラフ     ノード参照達と辺参照達の2つを持つだけ
// 辿りは「ノード参照 → 自分が繋がる辺参照 → その辺が繋ぐノード参照」の往復で
// 何段でも進む。参照同士は互いを保持せず (保持すると相互参照で構築できない)、
// 台帳 (実体プール2つへの参照) を持ち歩いて相手の参照をその場で組み立てる。
//
// 仕組みと具体の境界: 参照の「形」(実体+台帳、始点/終点の辿り) は仕組みが持つ。
// 具体に残るのは「名前」だけ — 個体の印 (太郎)、型の別名 (太郎参照)、
// メソッド名 (恋人の辺)。Rust の generics は名前を生成できないため、
// この名前の量産だけが graph! マクロの領分として残る。
//
// 仕組み (台帳・ノード参照・辺参照・ノードタグ・辺・結ぶ) は
// `src/仕組み.rs` の lib クレートへ移してある (issue #24 段階1)。
//
// 実行場所: C:\devs\Graphite\examples\graphitets-by-hand で
//   cargo run --bin static_graph
//   cargo test --bin static_graph
//
// このファイルは1ファイル100行の原則の例外である (区分: 再設計待ち)。この
// ファイルは150行を超える。このファイルは GraphiteTS の静的グラフ版を通常の
// Rust へ写す練習用ファイルである。扱いの判定は issue #28 のやること4 が行
// う。超過を許す根拠の台帳は `docs/development/line_count_ledger.md` にある。

