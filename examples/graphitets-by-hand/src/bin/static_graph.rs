// 静的グラフ版。ノードの顔ぶれがコンパイル時に確定しているドメイングラフを、
// ID も HashMap も使わずに表す (main.rs の動的グラフ版との対比)。
// 上から「仕組み (ドメインを知らない汎用層)」→「具体 (人間関係ドメイン)」の
// 順に並べ、依存は上から下への一方向にしてある。
//
// 参照はノード「型」ごとではなく、太郎・次郎のようなインスタンスごとに別の
// nominal 型 (太郎参照・次郎参照 等) にしてある。恋人()・男友達() のような
// メソッドは「その特定のインスタンスが実際に持つ関係」だけを生やす。
// これにより 次郎参照 には恋人() が存在せず、呼べば compile error になる。
// (以前の版は 太郎・次郎 を同じ 男参照 型で扱い、恋人() が Option を返し
// 実行時に ptr::eq で確かめていたが、あれは静的に分かることを実行時へ
// 追い出していた設計ミスだった)
//
// 実行場所: C:\devs\Graphite\examples\graphitets-by-hand で
//   cargo run --bin static_graph
//   cargo test --bin static_graph

// ---------------- 仕組み (ドメインを知らない汎用層) ----------------

// C# の Func<入力, 出力> に相当する読みやすい別名。
type 取り出す関数<From, To> = fn(&From) -> &To;

// 辺は「グラフから端点を取り出す関数」の組。fn ポインタは何も借用しないため、
// グラフ自身のフィールドに置いても自己参照 struct にならない。端点は必ず
// グラフのフィールドを指すので、「端点が存在しない」状態が型の上で書けない。
struct 辺<Graph, Start, End> {
    start: 取り出す関数<Graph, Start>,
    end: 取り出す関数<Graph, End>,
}
impl<Graph, Start, End> 辺<Graph, Start, End> {
    const fn 結ぶ(start: 取り出す関数<Graph, Start>, end: 取り出す関数<Graph, End>) -> Self { Self { start, end } }
    fn 始点<'a>(&self, g: &'a Graph) -> &'a Start { (self.start)(g) }
    fn 終点<'a>(&self, g: &'a Graph) -> &'a End { (self.end)(g) }
}

// ---------------- 具体 (人間関係ドメイン) ----------------

struct 男 {
    名前: String,
}
struct 女 {
    名前: String,
}

type 恋人関係 = 辺<人間関係グラフ, 男, 女>;
impl 恋人関係 {
    fn 男<'a>(&self, g: &'a 人間関係グラフ) -> &'a 男 { self.始点(g) }
    fn 女<'a>(&self, g: &'a 人間関係グラフ) -> &'a 女 { self.終点(g) }
}
type 男友達関係 = 辺<人間関係グラフ, 男, 男>;
impl 男友達関係 {
    fn 男1<'a>(&self, g: &'a 人間関係グラフ) -> &'a 男 { self.始点(g) }
    fn 男2<'a>(&self, g: &'a 人間関係グラフ) -> &'a 男 { self.終点(g) }
}
type 女友達関係 = 辺<人間関係グラフ, 女, 女>;
impl 女友達関係 {
    fn 女1<'a>(&self, g: &'a 人間関係グラフ) -> &'a 女 { self.始点(g) }
    fn 女2<'a>(&self, g: &'a 人間関係グラフ) -> &'a 女 { self.終点(g) }
}

struct 人間関係グラフ {
    太郎: 男,
    次郎: 男,
    花子: 女,
    桜: 女,
    太郎と花子: 恋人関係,
    太郎と次郎: 男友達関係,
    花子と桜: 女友達関係,
}

// 配線を読みやすくするための名前付き取り出し関数。
// クロージャ |g| &g.太郎 と同じ fn ポインタに畳まれ、実行時コストは変わらない。
fn 太郎を取り出す(g: &人間関係グラフ) -> &男 { &g.太郎 }
fn 次郎を取り出す(g: &人間関係グラフ) -> &男 { &g.次郎 }
fn 花子を取り出す(g: &人間関係グラフ) -> &女 { &g.花子 }
fn 桜を取り出す(g: &人間関係グラフ) -> &女 { &g.桜 }

impl 人間関係グラフ {
    fn new() -> Self {
        Self {
            太郎: 男 { 名前: "太郎".into() },
            次郎: 男 { 名前: "次郎".into() },
            花子: 女 { 名前: "花子".into() },
            桜: 女 { 名前: "桜".into() },
            太郎と花子: 恋人関係::結ぶ(太郎を取り出す, 花子を取り出す),
            太郎と次郎: 男友達関係::結ぶ(太郎を取り出す, 次郎を取り出す),
            花子と桜: 女友達関係::結ぶ(花子を取り出す, 桜を取り出す),
        }
    }
    fn 太郎(&self) -> 太郎参照<'_> { 太郎参照 { graph: self } }
    fn 次郎(&self) -> 次郎参照<'_> { 次郎参照 { graph: self } }
    fn 花子(&self) -> 花子参照<'_> { 花子参照 { graph: self } }
    fn 桜(&self) -> 桜参照<'_> { 桜参照 { graph: self } }
}

// インスタンスごとの参照型。太郎参照・次郎参照はどちらも中身は男だが、
// 別の nominal 型なので、恋人() を 太郎参照 にしか生やさなければ
// 次郎参照.恋人() は compile error になる。
struct 太郎参照<'g> {
    graph: &'g 人間関係グラフ,
}
impl<'g> 太郎参照<'g> {
    fn 名前(&self) -> &'g str { &self.graph.太郎.名前 }
    fn 恋人(&self) -> 花子参照<'g> { 花子参照 { graph: self.graph } }
    fn 男友達(&self) -> 次郎参照<'g> { 次郎参照 { graph: self.graph } }
}

struct 次郎参照<'g> {
    graph: &'g 人間関係グラフ,
}
impl<'g> 次郎参照<'g> {
    fn 名前(&self) -> &'g str { &self.graph.次郎.名前 }
    // 次郎はこのグラフのどの辺の始点にもなっていないため、
    // 恋人()・男友達() に相当するメソッドは存在しない。
}

struct 花子参照<'g> {
    graph: &'g 人間関係グラフ,
}
impl<'g> 花子参照<'g> {
    fn 名前(&self) -> &'g str { &self.graph.花子.名前 }
    fn 女友達(&self) -> 桜参照<'g> { 桜参照 { graph: self.graph } }
}

struct 桜参照<'g> {
    graph: &'g 人間関係グラフ,
}
impl<'g> 桜参照<'g> {
    fn 名前(&self) -> &'g str { &self.graph.桜.名前 }
    // 桜も同様に、始点になっている辺が無いためメソッドが無い。
}

fn main() {
    let g = 人間関係グラフ::new();
    println!(
        "全員: {} {} {} {}",
        g.太郎().名前(),
        g.次郎().名前(),
        g.花子().名前(),
        g.桜().名前()
    );
    println!("太郎の恋人: {}", g.太郎().恋人().名前());
    println!("太郎の男友達: {}", g.太郎().男友達().名前());
    println!("恋人の女友達: {}", g.太郎().恋人().女友達().名前());
    println!("太郎と花子: {} と {}", g.太郎と花子.男(&g).名前, g.太郎と花子.女(&g).名前);
    println!("太郎と次郎: {} と {}", g.太郎と次郎.男1(&g).名前, g.太郎と次郎.男2(&g).名前);
    println!("花子と桜: {} と {}", g.花子と桜.女1(&g).名前, g.花子と桜.女2(&g).名前);

    // 次郎参照.恋人() や 桜参照.女友達() は書くとコンパイルエラーになる (実測済み):
    //   g.次郎().恋人();
    //   error[E0599]: no method named `恋人` found for struct `次郎参照<'g>`
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 参照経由でチェーンして辿れる() {
        let g = 人間関係グラフ::new();
        assert_eq!(g.太郎().恋人().名前(), "花子");
        assert_eq!(g.太郎().男友達().名前(), "次郎");
        assert_eq!(g.太郎().恋人().女友達().名前(), "桜");
    }

    #[test]
    fn 辺のドメイン名アクセサで辿れる() {
        let g = 人間関係グラフ::new();
        assert_eq!(g.太郎と花子.男(&g).名前, "太郎");
        assert_eq!(g.太郎と花子.女(&g).名前, "花子");
        assert_eq!(g.太郎と次郎.男1(&g).名前, "太郎");
        assert_eq!(g.太郎と次郎.男2(&g).名前, "次郎");
        assert_eq!(g.花子と桜.女1(&g).名前, "花子");
        assert_eq!(g.花子と桜.女2(&g).名前, "桜");
    }
}
