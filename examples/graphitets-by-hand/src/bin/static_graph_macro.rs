// 静的グラフ版のマクロ利用側。static_graph.rs (手書き到達点) が人力で書いていた
// 「具体・参照の層」を 静的グラフ! マクロに生成させ、同じグラフ・同じテストが
// 通ることを確認する (issue #24 段階1)。
//
// マクロが生成するのは4種 (個体タグ・ノード達・辺達・型別名+所属辺メソッド+
// 参照の層+グラフ本体)。種別 (恋人・友達)・実体型 (男・女)・種別ごとの端点
// アクセサ (男()/女()・友達1()/友達2()) と、実体が名前を持つという契約
// (名前持ち・名前アクセス) はマクロの外、このファイルに書く。
//
// 実行場所: C:\devs\Graphite\examples\graphitets-by-hand で
//   cargo run --bin static_graph_macro
//   cargo test --bin static_graph_macro

use graphitets_by_hand::仕組み::*;
use graphitets_by_hand_macros::静的グラフ;

// ---------------- 具体: 実体の層 (マクロの外、手書き版と同じ) ----------------

trait 名前持ち {
    fn 名前(&self) -> &str;
}
struct 男 {
    名前: String,
}
impl 名前持ち for 男 {
    fn 名前(&self) -> &str { &self.名前 }
}
struct 女 {
    名前: String,
}
impl 名前持ち for 女 {
    fn 名前(&self) -> &str { &self.名前 }
}

// 関係の種類。種別ラベル (unit struct) は結ぶ() へ値として渡すためマクロの
// 外で用意する。
struct 恋人;
struct 友達;

// ---------------- 具体: 参照の層 (マクロが生成する) ----------------

#[rustfmt::skip]
静的グラフ! {
    graph 人間関係グラフ;
    node 太郎: 男;
    node 次郎: 男;
    node 一郎: 男;
    node 花子: 女;
    node 桜: 女;
    node 恵子: 女;
    edge 太郎と花子 = 恋人(太郎 -> 花子);
    edge 次郎と桜 = 恋人(次郎 -> 桜);
    edge 太郎と次郎 = 友達(太郎 -> 次郎);
    edge 太郎と一郎 = 友達(太郎 -> 一郎);
    edge 花子と桜 = 友達(花子 -> 桜);
    edge 花子と恵子 = 友達(花子 -> 恵子);
}

// ---------------- 具体: 種別ごとの端点アクセサ (マクロの外) ----------------
//
// 名前()・男()/女()・友達1()/友達2() は、生成された{graph名}ノード参照/
// {graph名}辺参照 が foreign な仕組みの型 (lib クレート) への型別名であるため、
// 孤児規則 (E0116) によりローカル trait + blanket impl で書く
// (issue #24 段階1で発見。詳細は static_graph.rs のコメント参照)。

trait 名前アクセス<'a> {
    fn 名前(&self) -> &'a str;
}
impl<'a, タグ: ノードタグ> 名前アクセス<'a> for 人間関係グラフノード参照<'a, タグ>
where
    タグ::実体: 名前持ち,
{
    fn 名前(&self) -> &'a str { self.実体.名前() }
}

trait 恋人アクセス<'a> {
    type 男側: ノードタグ;
    type 女側: ノードタグ;
    fn 男(&self) -> 人間関係グラフノード参照<'a, Self::男側>;
    fn 女(&self) -> 人間関係グラフノード参照<'a, Self::女側>;
}
impl<'a, 男側タグ, 女側タグ> 恋人アクセス<'a> for 人間関係グラフ辺参照<'a, 恋人, 男側タグ, 女側タグ>
where
    男側タグ: ノードタグ<実体 = 男>,
    女側タグ: ノードタグ<実体 = 女>,
{
    type 男側 = 男側タグ;
    type 女側 = 女側タグ;
    fn 男(&self) -> 人間関係グラフノード参照<'a, 男側タグ> { self.始点() }
    fn 女(&self) -> 人間関係グラフノード参照<'a, 女側タグ> { self.終点() }
}
trait 友達アクセス<'a> {
    type 甲側: ノードタグ;
    type 乙側: ノードタグ;
    fn 友達1(&self) -> 人間関係グラフノード参照<'a, Self::甲側>;
    fn 友達2(&self) -> 人間関係グラフノード参照<'a, Self::乙側>;
}
impl<'a, 甲タグ: ノードタグ, 乙タグ: ノードタグ> 友達アクセス<'a> for 人間関係グラフ辺参照<'a, 友達, 甲タグ, 乙タグ> {
    type 甲側 = 甲タグ;
    type 乙側 = 乙タグ;
    fn 友達1(&self) -> 人間関係グラフノード参照<'a, 甲タグ> { self.始点() }
    fn 友達2(&self) -> 人間関係グラフノード参照<'a, 乙タグ> { self.終点() }
}

fn main() {
    let ノード達 = ノード達::new(
        男 { 名前: "太郎".into() },
        男 { 名前: "次郎".into() },
        男 { 名前: "一郎".into() },
        女 { 名前: "花子".into() },
        女 { 名前: "桜".into() },
        女 { 名前: "恵子".into() },
    );
    let 辺達 = 辺達::張る(&ノード達);
    let g = 人間関係グラフ::new(&ノード達, &辺達);

    let 太郎の参照 = g.ノード参照達.太郎;
    println!("太郎の恋人: {}", 太郎の参照.太郎と花子().女().名前());
    println!(
        "太郎の恋人の友達の桜の恋人: {}",
        太郎の参照.太郎と花子().女().花子と桜().友達2().次郎と桜().男().名前()
    );
    println!(
        "一郎の友達の太郎の恋人: {}",
        g.ノード参照達.一郎.太郎と一郎().友達1().太郎と花子().女().名前()
    );
    println!("次郎の友達: {}", g.ノード参照達.次郎.太郎と次郎().友達1().名前());
    println!("花子の友達: {} と {}", g.ノード参照達.花子.花子と桜().友達2().名前(), g.ノード参照達.花子.花子と恵子().友達2().名前());
    println!("恵子の友達: {}", g.ノード参照達.恵子.花子と恵子().友達1().名前());
    println!("辺参照から: {} と {}", g.辺参照達.太郎と花子.男().名前(), g.辺参照達.太郎と花子.女().名前());
    println!("辺参照から: {} と {}", g.辺参照達.太郎と一郎.友達1().名前(), g.辺参照達.太郎と一郎.友達2().名前());
    println!("辺参照から: {} と {}", g.辺参照達.次郎と桜.男().名前(), g.辺参照達.次郎と桜.女().名前());
    println!("辺参照から: {} と {}", g.辺参照達.花子と恵子.友達1().名前(), g.辺参照達.花子と恵子.友達2().名前());
    println!("太郎の友達: {} と {}", 太郎の参照.太郎と次郎().友達2().名前(), 太郎の参照.太郎と一郎().友達2().名前());
    println!("桜の恋人: {}", g.ノード参照達.桜.次郎と桜().男().名前());
    println!("桜の友達: {}", g.ノード参照達.桜.花子と桜().友達1().名前());
    println!("花子の恋人: {}", g.ノード参照達.花子.太郎と花子().男().名前());
    println!("次郎の恋人: {}", g.ノード参照達.次郎.次郎と桜().女().名前());
    println!(
        "辺参照から: {} と {}",
        g.辺参照達.太郎と次郎.友達1().太郎と一郎().友達2().太郎と一郎().友達1().名前(),
        g.辺参照達.花子と桜.友達2().名前()
    );

    // 存在しない辿りがコンパイルエラーになることの実測 (2026-08-30):
    // 次郎参照 は 太郎と花子 の辺に繋がっていないため、次郎参照 (= 次郎の辺
    // トレイトを実装しない型) に太郎と花子() メソッドは生成されず、次の1行を
    // 実際にアンコメントしてビルドすると
    // 「E0599: no method named `太郎と花子` found for struct
    //   `graphitets_by_hand::仕組み::ノード参照<'_, ノード達, 辺達<'_>, 次郎>`」
    // (候補として 太郎の辺・花子の辺 が提示され、次郎の辺 は出ない) になる
    // ことを確認済み。
    // g.ノード参照達.次郎.太郎と花子();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ノード参照と辺参照を往復して何段でも辿れる() {
        let ノード達 = ノード達::new(
            男 { 名前: "太郎".into() },
            男 { 名前: "次郎".into() },
            男 { 名前: "一郎".into() },
            女 { 名前: "花子".into() },
            女 { 名前: "桜".into() },
            女 { 名前: "恵子".into() },
        );
        let 辺達 = 辺達::張る(&ノード達);
        let g = 人間関係グラフ::new(&ノード達, &辺達);
        assert_eq!(
            g.ノード参照達.太郎.太郎と花子().女().花子と桜().友達2().次郎と桜().男().名前(),
            "次郎"
        );
    }

    #[test]
    fn 辿った先は宣言された実体と同一インスタンスである() {
        let ノード達 = ノード達::new(
            男 { 名前: "太郎".into() },
            男 { 名前: "次郎".into() },
            男 { 名前: "一郎".into() },
            女 { 名前: "花子".into() },
            女 { 名前: "桜".into() },
            女 { 名前: "恵子".into() },
        );
        let 辺達 = 辺達::張る(&ノード達);
        let g = 人間関係グラフ::new(&ノード達, &辺達);
        assert!(std::ptr::eq(g.ノード参照達.太郎.太郎と花子().女().実体, &ノード達.花子));
        assert!(std::ptr::eq(g.辺参照達.太郎と花子.男().実体, g.ノード参照達.太郎.実体));
    }

    #[test]
    fn ノード参照が返す辺参照は辺参照達のものと同じ実体を指す() {
        let ノード達 = ノード達::new(
            男 { 名前: "太郎".into() },
            男 { 名前: "次郎".into() },
            男 { 名前: "一郎".into() },
            女 { 名前: "花子".into() },
            女 { 名前: "桜".into() },
            女 { 名前: "恵子".into() },
        );
        let 辺達 = 辺達::張る(&ノード達);
        let g = 人間関係グラフ::new(&ノード達, &辺達);
        assert!(std::ptr::eq(
            g.ノード参照達.太郎.太郎と花子().実体,
            g.辺参照達.太郎と花子.実体
        ));
    }
}
