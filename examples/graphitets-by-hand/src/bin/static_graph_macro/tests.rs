// static_graph_macro のアサーション (issue #24 段階2)。§3で確認した性質を
// アサーションで固定する: 役割アクセサでの複数段の辿り・積み荷アクセス・
// 無向辺の端点アクセス・同一インスタンス性。

use super::*;

#[test]
fn 役割アクセサで複数段辿れる() {
    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert_eq!(g.ノード参照達.太郎.太郎の上司().superior().次郎の所属().team().名前(), "開発部");
}

#[test]
fn 積み荷へ役割名のアクセサでアクセスできる() {
    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert_eq!(g.辺参照達.太郎の上司.任命().任命日, 2020);
}

#[test]
fn 無向辺は端点1と端点2で両端を返す() {
    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert_eq!(g.辺参照達.太郎と次郎.端点1().名前(), "太郎");
    assert_eq!(g.辺参照達.太郎と次郎.端点2().名前(), "次郎");
}

#[test]
fn 辿った先は宣言された実体と同一インスタンスである() {
    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert!(std::ptr::eq(g.ノード参照達.太郎.太郎の上司().superior().実体, &ノード達.次郎));
    assert!(std::ptr::eq(g.辺参照達.太郎の上司.subordinate().実体, g.ノード参照達.太郎.実体));
}

#[test]
fn ノード参照が返す辺参照は辺参照達のものと同じ実体を指す() {
    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert!(std::ptr::eq(g.ノード参照達.太郎.太郎の所属().実体, g.辺参照達.太郎の所属.実体));
}
