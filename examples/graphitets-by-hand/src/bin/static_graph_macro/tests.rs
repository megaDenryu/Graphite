#[test]
fn 無向辺は宣言した役割名のアクセサで両端を返す() {
    let ノード達 = ノード達を作る();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert_eq!(g.辺参照達.太郎と次郎.甲().実体().名前(), "太郎");
    assert_eq!(g.辺参照達.太郎と次郎.乙().実体().名前(), "次郎");
}

#[test]
fn 辿った先は宣言された実体と同一インスタンスである() {
    let ノード達 = ノード達を作る();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);
    assert!(std::ptr::eq(g.ノード参照達.太郎.太郎の上司().superior().実体, &ノード達.次郎));
    assert!(std::ptr::eq(g.辺参照達.太郎の上司.subordinate().実体, g.ノード参照達.太郎.実体));
}

