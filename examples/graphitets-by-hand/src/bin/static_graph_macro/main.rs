// (社員・部署・任命記録、hello-graphのOrgの和訳写し) で、レイヤー1
// (静的グラフ型!、schema相当) とレイヤー2 (静的グラフ!、graph!リテラル相当)
// の2マクロが、本体 (Graphite本体crateのgraph_schema!/graph!) に忠実な矢印
// 記法・役割名で骨組みと具体グラフを宣言し、役割アクセサ・積み荷アクセサ・
