use graphitets_by_hand::仕組み::*;
use graphitets_by_hand_macros::{静的グラフ, 静的グラフ型};

// ---------------- 具体: 実体の層 (マクロの外) ----------------

trait 名前持ち {
    fn 名前(&self) -> &str;
}
struct 社員 {
    名前: String,
}
impl 名前持ち for 社員 {
    fn 名前(&self) -> &str { &self.名前 }
}
struct 部署 {
    名前: String,
}
impl 名前持ち for 部署 {
    fn 名前(&self) -> &str { &self.名前 }
}
struct 任命記録 {
    任命日: i32,
}

// ---------------- レイヤー1: schema (骨組み) ----------------

静的グラフ型! {
    schema 組織 {
        node 社員;
        node 部署;
        edge 所属 = (member: 社員) -> (team: 部署) where each member: 1;
        edge 上司 = (subordinate: 社員) -[任命: 任命記録]-> (superior: 社員) where each subordinate: 0..1;
        edge 友人 = 社員 -- 社員;
    }
}

// ---------------- レイヤー2: リテラル (具体グラフ) ----------------

#[rustfmt::skip]
静的グラフ! {
    graph 開発チーム: 組織;
    太郎 = 社員 { 名前: "太郎".into() },
    次郎 = 社員 { 名前: "次郎".into() },
    開発部 = 部署 { 名前: "開発部".into() },
    太郎の所属 = 所属(太郎 -> 開発部),
    次郎の所属 = 所属(次郎 -> 開発部),
    太郎の上司 = 上司(太郎 -[任命記録 { 任命日: 2020 }]-> 次郎),
    太郎と次郎 = 友人(太郎 -- 次郎),
}

// ---------------- 具体: 名前アクセサ (マクロの外) ----------------
//
// 名前() は「実体が名前を持つ」ことだけを条件にした1つのtrait + blanket impl
// で全個体分をまかなう。{グラフ名}ノード参照 はforeignな仕組みの型への型別名
// であるため、孤児規則 (E0116) によりローカルtrait + implで書く
// (issue #24 段階1で発見。詳細はstatic_graph.rsのコメント参照)。

trait 名前アクセス<'a> {
    fn 名前(&self) -> &'a str;
}
impl<'a, タグ: ノードタグ> 名前アクセス<'a> for 開発チームノード参照<'a, タグ>
where
    タグ::実体: 名前持ち,
{
    fn 名前(&self) -> &'a str { self.実体.名前() }
}

fn main() {
    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);

    let 太郎の参照 = g.ノード参照達.太郎;
    println!("太郎の上司: {}", 太郎の参照.太郎の上司().superior().名前());
    println!("太郎の上司の任命日: {}", 太郎の参照.太郎の上司().任命().任命日);
    println!("太郎の上司の所属先: {}", 太郎の参照.太郎の上司().superior().次郎の所属().team().名前());
    println!("太郎の所属先: {}", 太郎の参照.太郎の所属().team().名前());
    println!("太郎の所属元 (辺参照から): {}", g.辺参照達.太郎の所属.member().名前());
    println!("太郎の友人 (無向辺の端点): {} と {}", g.辺参照達.太郎と次郎.端点1().名前(), g.辺参照達.太郎と次郎.端点2().名前());
    println!("次郎の所属先: {}", g.ノード参照達.次郎.次郎の所属().team().名前());
    println!("上司関係の部下 (辺参照から): {}", g.辺参照達.太郎の上司.subordinate().名前());

    // 存在しない辿りがコンパイルエラーになることの実測 (issue #24 段階2、
    // 2026-08-30):
    // 太郎 は 次郎の所属 辺の端点ではないため、太郎参照 に 次郎の所属()
    // メソッドは生成されず、次の1行を実際にアンコメントしてビルドすると
    // 「E0599: no method named `次郎の所属` found for struct
    //   `graphitets_by_hand::仕組み::ノード参照<'a, ノード達型, 辺達型, タグ>`
    //   in the current scope」(候補として 次郎の辺・開発部の辺 が提示され、
    //   太郎の辺 は出ない) になることを確認済み。
    // 太郎の参照.次郎の所属();

    // 多重度制約違反がコンパイルエラーになることの実測 (issue #24 段階2、
    // 2026-08-30): 上のリテラルから `太郎の所属 = 所属(太郎 -> 開発部),` の
    // 1行を一時的に削除してビルドすると、`each member: 1` 制約 (下限1) に対し
    // 太郎の所属件数が0になり、レイヤー1が生成したconst assertが
    // 「error[E0080]: evaluation panicked: 多重度制約違反: 太郎 の 所属
    //   (始点) の本数が範囲外です」というメッセージでコンパイルエラーになる
    // ことを確認済み (const評価時のpanicとして報告される)。確認後は1行を元に
    // 戻してある。
}
