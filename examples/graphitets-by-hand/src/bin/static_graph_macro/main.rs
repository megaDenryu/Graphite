// 静的グラフ型!/組織! (静的グラフ型!が生成するmacro_rules!) マクロ利用側
// (issue #24 段階2)。組織ドメイン (社員・部署・任命記録・経緯記録) で、
// schema宣言 (静的グラフ型!) とinstance宣言 (schema名そのものを名前にした
// macro_rules!、ここでは 組織!) の2段構えが、本体 (Graphite本体crateの
// graph_schema!/graph!) に忠実な矢印記法・役割名の構文で骨組みと具体グラフを
// 宣言し、役割アクセサ・積み荷アクセサ・無向辺の端点アクセサ・多重度検査・
// 対一意検査が機能することを確認する。
//
// マクロが生成するのは全部具象のコード (辺値struct・ノード達・辺達・個体
// ごとの参照struct・辺インスタンスごとの参照struct・参照の層の集まり・
// グラフ本体)。実体型 (社員・部署・任命記録・経緯記録) と「実体が名前を
// 持つ」という契約 (名前持ち) はマクロの外、このファイルに書く。生成物は
// 具象ローカルstructなので孤児規則 (E0116) には落ちず、`.実体()` 経由で
// 普通に 名前持ち を呼べる (前版の版のブランケットimpl迂回が不要になった)。
//
// 静的グラフ型! が生成する macro_rules! は通常のmacro_rules!と同じテキスト
// 順の制約を持つ: `静的グラフ型! { schema 組織 { .. } }` より後ろでしか
// `組織! { .. }` を呼べない (詳細はREADME参照)。
//
// 実行場所: C:\devs\Graphite\examples\graphitets-by-hand で
//   cargo run --bin static_graph_macro
//   cargo test --bin static_graph_macro

#[cfg(test)]
mod tests;

use graphitets_by_hand_macros::静的グラフ型;

// ---------------- 具体: 実体の層 (マクロの外) ----------------

trait 名前持ち {
    fn 名前(&self) -> &str;
}
struct 社員 {
    名前: String,
}
impl 名前持ち for 社員 {
    fn 名前(&self) -> &str { &self.名前 }
}
struct 部署 {
    名前: String,
}
impl 名前持ち for 部署 {
    fn 名前(&self) -> &str { &self.名前 }
}
struct 任命記録 {
    任命日: i32,
}
struct 経緯記録 {
    経緯: String,
}

// `node 名前: 型 = 式;` (型注釈+任意式) が構造体リテラルに限らない任意の式を
// 受理することを実証するための、構造体リテラルではない式 (関数呼び出し)。
fn 社員を作る(名前: &str) -> 社員 {
    社員 { 名前: 名前.into() }
}

// ---------------- schema宣言 ----------------

静的グラフ型! {
    schema 組織 {
        node 社員;
        node 部署;
        edge 所属 = (member: 社員) -> (team: 部署) where each member: 1;
        edge 上司 = (subordinate: 社員) -[任命: 任命記録]-> (superior: 社員) where each subordinate: 0..1;
        edge 友人 = (甲: 社員) -- (乙: 社員) where unique pair;
        edge 同僚 = (甲: 社員) -[経緯: 経緯記録]- (乙: 社員);
    }
}

// ---------------- instance宣言 ----------------
//
// 開発部 だけを値なし宣言 (`node 開発部: 部署;`) にして、実行時供給
// (`ノード達::初期値` への位置引数) を実証する (issue #24 段階2)。
// main() とテストの両方から呼ぶため、構築を ノード達を作る() へ切り出す。

#[rustfmt::skip]
組織! {
    graph 開発チーム;
    node 太郎 = 社員 { 名前: "太郎".into() };
    node 次郎 = 社員 { 名前: "次郎".into() };
    node 一郎: 社員 = 社員を作る("一郎");
    node 開発部: 部署;
    edge 太郎の所属 = 所属(太郎 -> 開発部);
    edge 次郎の所属 = 所属(次郎 -> 開発部);
    edge 一郎の所属 = 所属(一郎 -> 開発部);
    edge 太郎の上司 = 上司(太郎 -[任命記録 { 任命日: 2020 }]-> 次郎);
    edge 太郎と次郎 = 友人(太郎 -- 次郎);
    edge 太郎と一郎の同僚 = 同僚(太郎 -[経緯記録 { 経緯: "同期入社".into() }]- 一郎);
}

// 値なし宣言 (開発部) の実体は実行時にここで供給する。3形態のうち
// `node 名前: 型 = 式;` (一郎、右辺は構造体リテラルでない関数呼び出し) と
// `node 名前: 型;` (開発部) の動作確認を兼ねる。
fn ノード達を作る() -> ノード達 {
    ノード達::初期値(部署 { 名前: "開発部".into() })
}

// 同一schemaから`組織!`を2回目に呼んでも、辺値struct群 (`{種別}の辺`) が
// 重複定義エラーにならないことの実証 (issue #24 段階2 コミット1)。辺値
// struct群は`静的グラフ型!`側 (schema単位、1回だけ展開) へ移してあるため、
// `組織!`呼び出しの回数に依らない。一方 `ノード達`/`辺達`/`ノード参照達`/
// `辺参照達`は`組織!`呼び出しごと (instance単位) に固定名で生成されるため、
// 同一スコープで2回展開すると重複定義になる。関数の本体は独立したアイテム
// スコープを持つため、この関数の中へ2つ目の呼び出しを閉じ込めて衝突を避ける
// (モジュールで分離する案は、macro_rules!の展開元がproc macroであるとき
// rust-analyzerがネストしたmodの中の呼び出しを解決できない既知の制約に
// 当たったため採らなかった)。この関数はmain()とtests.rsの両方から呼ぶ。
fn 経理チームを試す() -> String {
    #[rustfmt::skip]
    組織! {
        graph 経理チーム;
        node 花子 = 社員 { 名前: "花子".into() };
        node 総務部 = 部署 { 名前: "総務部".into() };
        edge 花子の所属 = 所属(花子 -> 総務部);
    }

    let ノード達 = ノード達::初期値();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 経理チーム::new(&ノード達, &辺達);
    g.ノード参照達.花子.花子の所属().team().実体().名前().to_string()
}

fn main() {
    let ノード達 = ノード達を作る();
    let 辺達 = 辺達::張る(&ノード達);
    let g = 開発チーム::new(&ノード達, &辺達);

    let 太郎の参照 = g.ノード参照達.太郎;
    println!("太郎の上司: {}", 太郎の参照.太郎の上司().superior().実体().名前());
    println!("太郎の上司の任命日: {}", 太郎の参照.太郎の上司().任命().任命日);
    println!("太郎の上司の所属先: {}", 太郎の参照.太郎の上司().superior().次郎の所属().team().実体().名前());
    println!("太郎の所属先: {}", 太郎の参照.太郎の所属().team().実体().名前());
    println!("太郎の所属元 (辺参照から): {}", g.辺参照達.太郎の所属.member().実体().名前());
    println!("太郎の友人 (無向辺の端点): {} と {}", g.辺参照達.太郎と次郎.甲().実体().名前(), g.辺参照達.太郎と次郎.乙().実体().名前());
    println!("太郎と一郎の同僚関係 (積み荷付き無向辺): {} と {} (経緯: {})", g.辺参照達.太郎と一郎の同僚.甲().実体().名前(), g.辺参照達.太郎と一郎の同僚.乙().実体().名前(), g.辺参照達.太郎と一郎の同僚.経緯().経緯);
    println!("次郎の所属先: {}", g.ノード参照達.次郎.次郎の所属().team().実体().名前());
    println!("上司関係の部下 (辺参照から): {}", g.辺参照達.太郎の上司.subordinate().実体().名前());
    println!("経理チームの花子の所属先 (同一schemaの2つ目のグラフ): {}", 経理チームを試す());

    // 存在しない辿りがコンパイルエラーになることの実測 (issue #24 段階2、
    // 2026-08-31): 太郎 は 次郎の所属 辺の端点ではないため、太郎参照 に
    // 次郎の所属() メソッドは生成されない。次の1行を実際にアンコメントして
    // ビルドすると、次のエラーになることを確認済み:
    //   error[E0599]: no method named `次郎の所属` found for struct
    //   `太郎参照<'a>` in the current scope
    //   help: there is a method `太郎の所属` with a similar name
    // 確認後はコメントアウトへ戻してある。
    // 太郎の参照.次郎の所属();

    // 多重度制約違反がコンパイルエラーになることの実測 (issue #24 段階2、
    // 2026-08-31): 上のinstance宣言から `edge 一郎の所属 = 所属(一郎 -> 開発部);`
    // の1行を一時的に削除してビルドすると、`each member: 1` 制約 (下限1) に
    // 対し一郎の所属件数が0になり、次のエラーで展開時にコンパイルエラーに
    // なることを確認済み (const評価時のpanicではなく通常のcompile_error!):
    //   error: 多重度制約違反: `一郎` の `所属` (役割 `member`) の本数が0件で、
    //   範囲 1..1 の外です
    // 確認後は1行を元に戻してある。

    // 対一意制約違反がコンパイルエラーになることの実測 (issue #24 段階2、
    // 2026-08-31): 上のinstance宣言へ
    // `edge 次郎と太郎 = 友人(次郎 -- 太郎);` (端点の順序を変えただけの重複) を
    // 一時的に追加してビルドすると、無向辺は端点の順序に依らず正規化して
    // 比較するため、次のエラーで展開時にコンパイルエラーになることを
    // 確認済み:
    //   error: 対一意制約違反: 種別 `友人` の辺 `次郎と太郎` は端点の組
    //   (太郎, 次郎) が既出の辺と重複しています
    // 確認後は追加した行を削除してある。
}
