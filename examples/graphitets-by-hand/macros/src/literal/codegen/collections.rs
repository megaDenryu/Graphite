// 生成物6: 参照の層の集まりとグラフ本体。ノード参照達・辺参照達はいずれも
// このマクロ展開先で新しく定義するローカル型なので、他の生成物と違って
// inherent implのままでよい (孤児規則の対象はforeignな型だけ)。無向辺の参照は
// 無向辺参照::new で組み立てる。

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::literal::input::{辺形状, 静的グラフ入力};

pub(super) fn 参照達とグラフを生成する(入力: &静的グラフ入力) -> TokenStream {
    let グラフ名 = &入力.グラフ名;
    let 台帳別名 = format_ident!("{}台帳", グラフ名);

    let ノード参照フィールド達 = 入力.ノード宣言達.iter().map(|ノード| {
        let 名前 = &ノード.名前;
        let 参照名 = format_ident!("{}参照", 名前);
        quote! { #名前: #参照名<'a> }
    });
    let ノード参照初期化達 = 入力.ノード宣言達.iter().map(|ノード| {
        let 名前 = &ノード.名前;
        quote! { #名前: ノード参照::new(&ノード達.#名前, 台帳) }
    });
    let 辺参照フィールド達 = 入力.辺宣言達.iter().map(|辺| {
        let 名前 = &辺.名前;
        let 参照名 = format_ident!("{}参照", 名前);
        quote! { #名前: #参照名<'a> }
    });
    let 辺参照初期化達 = 入力.辺宣言達.iter().map(|辺| {
        let 名前 = &辺.名前;
        let 構築関数 = match &辺.形状 {
            辺形状::有向 { .. } => quote! { 辺参照::new },
            辺形状::無向 { .. } => quote! { 無向辺参照::new },
        };
        quote! { #名前: #構築関数(&辺達.#名前, 台帳) }
    });

    quote! {
        struct ノード参照達<'a> {
            #(#ノード参照フィールド達,)*
        }
        impl<'a> ノード参照達<'a> {
            fn 作る(台帳: #台帳別名<'a>) -> Self {
                let ノード達 = 台帳.ノード達;
                Self { #(#ノード参照初期化達,)* }
            }
        }

        struct 辺参照達<'a> {
            #(#辺参照フィールド達,)*
        }
        impl<'a> 辺参照達<'a> {
            fn 作る(台帳: #台帳別名<'a>) -> Self {
                let 辺達 = 台帳.辺達;
                Self { #(#辺参照初期化達,)* }
            }
        }

        struct #グラフ名<'a> {
            ノード参照達: ノード参照達<'a>,
            辺参照達: 辺参照達<'a>,
        }
        impl<'a> #グラフ名<'a> {
            fn new(ノード達: &'a ノード達, 辺達: &'a 辺達<'a>) -> Self {
                let 台帳 = 台帳 { ノード達, 辺達 };
                Self {
                    ノード参照達: ノード参照達::作る(台帳),
                    辺参照達: 辺参照達::作る(台帳),
                }
            }
        }
    }
}
