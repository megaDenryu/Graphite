// 生成物4a: 型別名。仕組みのジェネリック型 (台帳・ノード参照・辺参照・
// 無向辺参照) を、このグラフ専用の名前へ畳む。個別の辺参照エイリアスは積み荷
// 型を `<種別 as 種別契約>::積み荷` の射影で書く (レイヤー2は具体の積み荷型を
// 知らないため。射影は型検査の段階でレイヤー1のimplにより正規化される)。

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::literal::input::{ノード宣言, 辺形状, 辺宣言, 静的グラフ入力};

pub(super) fn 型別名達を生成する(入力: &静的グラフ入力) -> TokenStream {
    let グラフ名 = &入力.グラフ名;
    let 台帳別名 = format_ident!("{}台帳", グラフ名);
    let ノード参照別名 = format_ident!("{}ノード参照", グラフ名);
    let 辺参照別名 = format_ident!("{}辺参照", グラフ名);
    let 無向辺参照別名 = format_ident!("{}無向辺参照", グラフ名);

    let ノード参照個別達 = 入力.ノード宣言達.iter().map(|ノード: &ノード宣言| {
        let 名前 = &ノード.名前;
        let 参照名 = format_ident!("{}参照", 名前);
        quote! { type #参照名<'a> = #ノード参照別名<'a, #名前>; }
    });
    let 辺参照個別達 = 入力.辺宣言達.iter().map(|辺: &辺宣言| {
        let 名前 = &辺.名前;
        let 参照名 = format_ident!("{}参照", 名前);
        let 種別 = &辺.種別;
        match &辺.形状 {
            辺形状::有向 { 始点, 終点, .. } => {
                quote! { type #参照名<'a> = #辺参照別名<'a, #種別, #始点, #終点, <#種別 as 種別契約>::積み荷>; }
            }
            辺形状::無向 { 端点1, 端点2 } => {
                quote! { type #参照名<'a> = #無向辺参照別名<'a, #種別, #端点1, #端点2, <#種別 as 種別契約>::積み荷>; }
            }
        }
    });

    quote! {
        type #台帳別名<'a> = 台帳<'a, ノード達, 辺達<'a>>;
        type #ノード参照別名<'a, タグ> = ノード参照<'a, ノード達, 辺達<'a>, タグ>;
        type #辺参照別名<'a, 種別, 始点タグ, 終点タグ, 積み荷> = 辺参照<'a, ノード達, 辺達<'a>, 種別, 始点タグ, 終点タグ, 積み荷>;
        type #無向辺参照別名<'a, 種別, 端点1タグ, 端点2タグ, 積み荷> = 無向辺参照<'a, ノード達, 辺達<'a>, 種別, 端点1タグ, 端点2タグ, 積み荷>;
        #(#ノード参照個別達)*
        #(#辺参照個別達)*
    }
}
