// 生成物3: 辺達。辺の実体の唯一の所有者。フィールド型は
// 辺<'a, 種別, 始点実体型, 終点実体型, <種別 as 種別契約>::積み荷> / 無向辺<..>
// を直に書く。積み荷の具体型はレイヤー1のみが知るため、常に種別契約からの
// 射影で書く (積み荷なしの種別は射影が () に正規化される)。

use std::collections::HashMap;

use proc_macro2::{Ident, TokenStream};
use quote::quote;

use crate::literal::input::{辺中身, 辺形状, 辺宣言};

pub(super) fn 辺達を生成する(辺宣言達: &[辺宣言], 実体型索引: &HashMap<String, Ident>) -> TokenStream {
    let フィールド達 = 辺宣言達.iter().map(|辺| フィールドを生成する(辺, 実体型索引));
    let 配線達 = 辺宣言達.iter().map(配線を生成する);
    quote! {
        struct 辺達<'a> {
            #(#フィールド達,)*
        }
        impl<'a> 辺達<'a> {
            fn 張る(ノード達: &'a ノード達) -> Self {
                Self { #(#配線達,)* }
            }
        }
    }
}

fn フィールドを生成する(辺: &辺宣言, 実体型索引: &HashMap<String, Ident>) -> TokenStream {
    let 名前 = &辺.名前;
    let 種別 = &辺.種別;
    match &辺.形状 {
        辺形状::有向 { 始点, 終点, .. } => {
            let 始点型 = &実体型索引[&始点.to_string()];
            let 終点型 = &実体型索引[&終点.to_string()];
            quote! { #名前: 辺<'a, #種別, #始点型, #終点型, <#種別 as 種別契約>::積み荷> }
        }
        辺形状::無向 { 端点1, 端点2 } => {
            let 型1 = &実体型索引[&端点1.to_string()];
            let 型2 = &実体型索引[&端点2.to_string()];
            quote! { #名前: 無向辺<'a, #種別, #型1, #型2, <#種別 as 種別契約>::積み荷> }
        }
    }
}

fn 配線を生成する(辺: &辺宣言) -> TokenStream {
    let 名前 = &辺.名前;
    let 種別 = &辺.種別;
    match &辺.形状 {
        辺形状::有向 { 始点, 終点, 中身: 辺中身::無Payload } => {
            quote! { #名前: 結ぶ(#種別, &ノード達.#始点, &ノード達.#終点) }
        }
        辺形状::有向 { 始点, 終点, 中身: 辺中身::Payload(式) } => {
            quote! { #名前: 積んで結ぶ(#種別, &ノード達.#始点, &ノード達.#終点, #式) }
        }
        辺形状::無向 { 端点1, 端点2 } => {
            quote! { #名前: 無向に結ぶ(#種別, &ノード達.#端点1, &ノード達.#端点2) }
        }
    }
}
