// 生成物5: 多重度・対一意のconst assert。レイヤー1が生成した多重度契約
// (種別ごとの多重度trait) を、レイヤー2の入力トークン (個体名・種別名・矢印の
// 向き) だけから機械的に組み立てて参照する。役割名はレイヤー2の入力に出て
// こないため、位置キー版のtrait ({種別}の多重度<始点位置|終点位置>) を使う。
//
// 検査対象は「その種別のその位置に実際に使われている実体型」と同じ実体型を
// 持つ、グラフに登場する全個体 (その個体自身がその種別の辺に繋がっているかは
// 問わない)。これにより、1本もその種別の辺を持たない個体の下限違反
// (例: each member: 1 に対して所属辺が0本) も検出できる。
//
// schemaにあるがこのリテラルで1回も使われない種別は、走査対象そのものに
// 現れないため検査されない (issue #24 段階2で判明した既知の限界)。

use std::collections::HashSet;

use proc_macro2::{Ident, TokenStream};
use quote::{format_ident, quote};

use crate::literal::input::{辺形状, 辺宣言, 静的グラフ入力};

pub(super) fn 多重度検査達を生成する(入力: &静的グラフ入力) -> TokenStream {
    let 位置検査達 = 位置ごとの検査を生成する(入力);
    let 対一意検査達 = 対一意検査達を生成する(入力);
    quote! { #(#位置検査達)* #(#対一意検査達)* }
}

// (種別名, 位置ラベル, 実体型名) の組を一度だけ検査すればよいので、走査済みの
// 組を記録しながら辺宣言達を舐める。
fn 位置ごとの検査を生成する(入力: &静的グラフ入力) -> Vec<TokenStream> {
    let mut 済み: HashSet<(String, &'static str, String)> = HashSet::new();
    let mut 検査達 = Vec::new();

    for 辺 in &入力.辺宣言達 {
        let (始点, 終点) = match &辺.形状 {
            辺形状::有向 { 始点, 終点, .. } => (始点, 終点),
            辺形状::無向 { .. } => continue,
        };
        for (個体, 位置ラベル) in [(始点, "始点"), (終点, "終点")] {
            let 型 = 実体型を求める(入力, 個体);
            let キー = (辺.種別.to_string(), 位置ラベル, 型.to_string());
            if !済み.insert(キー) {
                continue;
            }
            検査達.push(一件分の位置検査を生成する(入力, &辺.種別, 位置ラベル, 型));
        }
    }
    検査達
}

fn 一件分の位置検査を生成する(入力: &静的グラフ入力, 種別: &Ident, 位置ラベル: &str, 対象型: &Ident) -> TokenStream {
    let トレイト名 = format_ident!("{}の多重度", 種別);
    let 位置トークン = if 位置ラベル == "始点" { quote! { 始点位置 } } else { quote! { 終点位置 } };

    let 検査達 = 入力.ノード宣言達.iter().filter(|n| &n.実体型 == 対象型).map(|n| {
        let 個体 = &n.名前;
        let 件数 = 入力.辺宣言達.iter().filter(|辺| 辺.種別 == *種別 && 指定位置の個体か(辺, 位置ラベル, 個体)).count();
        let メッセージ = format!("多重度制約違反: {} の {} ({}) の本数が範囲外です", 個体, 種別, 位置ラベル);
        quote! {
            const _: () = assert!(
                #件数 >= <#対象型 as #トレイト名<#位置トークン>>::下限
                    && #件数 <= <#対象型 as #トレイト名<#位置トークン>>::上限,
                #メッセージ,
            );
        }
    });
    quote! { #(#検査達)* }
}

fn 指定位置の個体か(辺: &辺宣言, 位置ラベル: &str, 個体: &Ident) -> bool {
    match (&辺.形状, 位置ラベル) {
        (辺形状::有向 { 始点, .. }, "始点") => 始点 == 個体,
        (辺形状::有向 { 終点, .. }, "終点") => 終点 == 個体,
        _ => false,
    }
}

fn 実体型を求める<'i>(入力: &'i 静的グラフ入力, 個体: &Ident) -> &'i Ident {
    &入力.ノード宣言達.iter().find(|n| &n.名前 == 個体).expect("検証済みなので端点は必ず宣言されている").実体型
}

fn 対一意検査達を生成する(入力: &静的グラフ入力) -> Vec<TokenStream> {
    let mut 種別達: Vec<&Ident> = Vec::new();
    for 辺 in &入力.辺宣言達 {
        if !種別達.iter().any(|s| **s == 辺.種別) {
            種別達.push(&辺.種別);
        }
    }
    種別達.into_iter().map(|種別| 一件分の対一意検査を生成する(入力, 種別)).collect()
}

fn 一件分の対一意検査を生成する(入力: &静的グラフ入力, 種別: &Ident) -> TokenStream {
    let ペア一覧: Vec<(String, String)> = 入力
        .辺宣言達
        .iter()
        .filter(|辺| 辺.種別 == *種別)
        .map(|辺| match &辺.形状 {
            辺形状::有向 { 始点, 終点, .. } => (始点.to_string(), 終点.to_string()),
            辺形状::無向 { 端点1, 端点2 } => (端点1.to_string(), 端点2.to_string()),
        })
        .collect();
    let 総数 = ペア一覧.len();
    let 相異数 = ペア一覧.iter().collect::<HashSet<_>>().len();
    let 重複数 = 総数 - 相異数;

    let トレイト名 = format_ident!("{}の対一意", 種別);
    let メッセージ = format!("対一意制約違反: {} に重複する端点の組があります", 種別);
    quote! {
        const _: () = assert!(
            !<#種別 as #トレイト名>::有効 || #重複数 == 0,
            #メッセージ,
        );
    }
}
