// 生成物3: 役割アクセサ。有向辺の種別ごとに、始点タグ・終点タグをジェネリック
// のまま残したローカルtrait + ブランケットimplを生成する (手書き到達点
// `static_graph.rs` の恋人アクセスパターンと同じ形)。無向辺には生成しない
// (仕組み側の端点1()/端点2()をそのまま使う)。
//
// レイヤー2はこのtraitの存在を一切知らなくてよい。レイヤー2が生成する個々の
// 個体タグは具体的なS/Tに過ぎず、ノードタグ<実体=X>を満たしさえすれば自動的に
// このimplの対象になる (Rustの型解決が自動で結ぶ)。

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::schema::input::{辺形状, 辺宣言};

pub(super) fn 役割アクセサ達を生成する(辺宣言達: &[辺宣言]) -> TokenStream {
    let 生成達 = 辺宣言達.iter().filter_map(一種別分を生成する);
    quote! { #(#生成達)* }
}

fn 一種別分を生成する(辺: &辺宣言) -> Option<TokenStream> {
    let (始点役割, 始点型, 積み荷, 終点役割, 終点型) = match &辺.形状 {
        辺形状::有向 { 始点役割, 始点型, 積み荷, 終点役割, 終点型 } => (始点役割, 始点型, 積み荷, 終点役割, 終点型),
        辺形状::無向 { .. } => return None,
    };

    let 種別 = &辺.名前;
    let トレイト名 = format_ident!("{}の端点", 種別);
    let 積み荷型 = match 積み荷 {
        Some((_, 型)) => quote! { #型 },
        None => quote! { () },
    };
    let 積み荷アクセサ宣言 = 積み荷.as_ref().map(|(役割, 型)| quote! { fn #役割(&self) -> &'a #型; });
    let 積み荷アクセサ実装 = 積み荷.as_ref().map(|(役割, _)| quote! { fn #役割(&self) -> &'a #積み荷型 { self.積み荷() } });

    Some(quote! {
        trait #トレイト名<'a, ノード達型, 辺達型, S, T>
        where
            S: ノードタグ<実体 = #始点型>,
            T: ノードタグ<実体 = #終点型>,
        {
            fn #始点役割(&self) -> ノード参照<'a, ノード達型, 辺達型, S>;
            fn #終点役割(&self) -> ノード参照<'a, ノード達型, 辺達型, T>;
            #積み荷アクセサ宣言
        }
        impl<'a, ノード達型, 辺達型, S, T> #トレイト名<'a, ノード達型, 辺達型, S, T>
            for 辺参照<'a, ノード達型, 辺達型, #種別, S, T, #積み荷型>
        where
            S: ノードタグ<実体 = #始点型>,
            T: ノードタグ<実体 = #終点型>,
        {
            fn #始点役割(&self) -> ノード参照<'a, ノード達型, 辺達型, S> { self.始点() }
            fn #終点役割(&self) -> ノード参照<'a, ノード達型, 辺達型, T> { self.終点() }
            #積み荷アクセサ実装
        }
    })
}
