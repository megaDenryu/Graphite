// 生成物4a: 型別名。仕組みのジェネリック型 (台帳・ノード参照・辺参照) を、
// このグラフ専用の名前へ畳む。graph名を接頭辞にするのはこの3つだけで、
// 個体・辺の参照別名はそれぞれの宣言名をそのまま使う (1グラフにつき1回しか
// 展開しない前提。複数グラフを1モジュールに同居させる場合の扱いは段階2の
// 検討事項)。

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::input::{ノード宣言, 辺宣言, 静的グラフ入力};

pub fn 型別名達を生成する(入力: &静的グラフ入力) -> TokenStream {
    let グラフ名 = &入力.グラフ名;
    let 台帳別名 = format_ident!("{}台帳", グラフ名);
    let ノード参照別名 = format_ident!("{}ノード参照", グラフ名);
    let 辺参照別名 = format_ident!("{}辺参照", グラフ名);

    let ノード参照個別達 = 入力.ノード宣言達.iter().map(|ノード: &ノード宣言| {
        let 名前 = &ノード.名前;
        let 参照名 = format_ident!("{}参照", 名前);
        quote! { type #参照名<'a> = #ノード参照別名<'a, #名前>; }
    });
    let 辺参照個別達 = 入力.辺宣言達.iter().map(|辺: &辺宣言| {
        let 名前 = &辺.名前;
        let 参照名 = format_ident!("{}参照", 名前);
        let 種別 = &辺.種別;
        let 始点 = &辺.始点;
        let 終点 = &辺.終点;
        quote! { type #参照名<'a> = #辺参照別名<'a, #種別, #始点, #終点>; }
    });

    quote! {
        type #台帳別名<'a> = 台帳<'a, ノード達, 辺達<'a>>;
        type #ノード参照別名<'a, タグ> = ノード参照<'a, ノード達, 辺達<'a>, タグ>;
        type #辺参照別名<'a, 種別, 始点タグ, 終点タグ> = 辺参照<'a, ノード達, 辺達<'a>, 種別, 始点タグ, 終点タグ>;
        #(#ノード参照個別達)*
        #(#辺参照個別達)*
    }
}
