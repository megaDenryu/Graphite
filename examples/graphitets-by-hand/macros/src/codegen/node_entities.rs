// 生成物2: ノード達。ノードの実体の唯一の所有者。フィールドはノード名、
// 値は new() の引数でランタイムに受け取る (issue #24: 実体の値の与え方は
// リテラル化するかを段階2で判断する未決の問い。段階1は構築関数で受ける形)。
//
// new() の引数名はノード名そのもの (太郎: 男) にはできない。同じ名前で
// 個体タグ (pub struct 太郎;) も生成しており、識別子 太郎 だけの引数パターンは
// 「新しい束縛」ではなく「unit struct 太郎 への照合」と解釈されてしまうため
// (E0308。issue #24 段階1で発見)。引数名には「の値」を足して衝突を避け、
// フィールド初期化は field: expr の完全形で書く (省略記法は使えない)。

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::input::ノード宣言;

pub fn ノード達を生成する(ノード宣言達: &[ノード宣言]) -> TokenStream {
    let フィールド達 = ノード宣言達.iter().map(|ノード| {
        let 名前 = &ノード.名前;
        let 実体型 = &ノード.実体型;
        quote! { #名前: #実体型 }
    });
    let 引数達 = ノード宣言達.iter().map(|ノード| {
        let 引数名 = format_ident!("{}の値", ノード.名前);
        let 実体型 = &ノード.実体型;
        quote! { #引数名: #実体型 }
    });
    let 初期化達 = ノード宣言達.iter().map(|ノード| {
        let 名前 = &ノード.名前;
        let 引数名 = format_ident!("{}の値", ノード.名前);
        quote! { #名前: #引数名 }
    });
    quote! {
        struct ノード達 {
            #(#フィールド達,)*
        }
        impl ノード達 {
            fn new(#(#引数達,)*) -> Self {
                Self { #(#初期化達,)* }
            }
        }
    }
}
