//! `cargo xtask` のコマンドラインの使い方の説明文。
//!
//! このファイルは説明文という1つのデータを持つ。文面は `main.rs` の引数解析と
//! 一緒に読む必要がなく、逆に説明文の途中で切ると1つの説明が複数ファイルへ散る。

// 検査の限界を書いておかないと、通ったことを「文書の内容が正しい」と読み違える。
pub(crate) const USAGE: &str = "\
使い方: リポジトリルートで次のいずれかを実行してください
  cargo xtask generate            生成ファイルを更新する
  cargo xtask generate --check    生成ファイルの差分と孤児 (どの schema 宣言からも参照されなくなった生成ファイル) をエラーにする
  cargo xtask check-external      ワークスペースの外の検証用パッケージで、生成の差分検査とビルドと clippy とテストを実行する
  cargo xtask check-docs          文書参照とリポジトリ内Rustソース参照の綴りの実在・行数範囲、docs/README.md 索引の網羅を検査する
  cargo xtask check-doc-comments  doc コメントが公開面に網羅され、内部領域に1件も無いことを検査する
  cargo xtask check-line-counts   1ファイル100行の原則と、例外台帳の登録の過不足を検査する

check-docs が検査するもの (crates・examples・xtask・verification 配下と
docs/history 配下の Rust ソースを指す参照): ファイルの実在と、行番号 (範囲や
カンマ区切りの複数指定) がその実ファイルの行数に収まっていること。無効な行指定、
およびワイルドカード・プレースホルダを含まないのに解析できない綴りは
「解析できないソース参照」として検査する。ワイルドカード (`*`) やプレースホルダ
(`<名前>` 等) を含む綴りは「該当するファイル群」を総称する散文とみなし、個別
ファイルへの参照として検査しない。

参照の直後に (空行だけを挟んで) コードフェンスが続く場合、check-docs はその本文を
引用とみなし2つの判定を行う。行範囲の妥当性は、引用の先頭3行が参照先の指定行範囲に
実在するかを見る。鮮度は、引用の全行が参照先ファイル全体のどこかに実在するかを見る。
空行・省略記号・正規化すると空になる行はどちらの判定も照合しない。一致とみなす差は
空白の違い・引数列の末尾コンマ・署名を `;` で打ち切った引用の3つである。引用として
取り込むのは情報文字列が `rust` のコードフェンスだけであり、
`docs/desugaring_reference.md` の冒頭が宣言する4つの改変 (先頭の字下げの除去・doc
コメント記号の除去・署名の1行化・出典範囲内の一部メソッドの無印省略) だけを原文との
違いとして許す。

check-docs が検査しないもの: Markdown の見出しへ飛ぶリンクの実在、引用の開始位置が
指定行範囲の先頭と揃っていること、引用行が現れる順序、ファイルの綴りを持たない裸の
行範囲とその直後のフェンス、参照とフェンスの間に散文が挟まる引用、1つの参照に続けて
並ぶ2つ目以降のフェンス、フェンスの中に書かれた参照の引用本文、引用が指定行範囲から
一字一句そのまま取られていること (生成物の一致は generate --check が担当)、Rust の
doc コメントに書いたコードフェンスの本文、行番号を持たない引用本文、外部URL、
`../` で始まる別リポジトリの文書 (件数だけ報告する)。

check-doc-comments が検査するもの: 内部領域に項目の doc コメント (`///` と
`#[doc = \"...\"]`) が1件も無いこと、生成コードの公開面 (crates・examples・
verification 配下の generated ディレクトリ) の非 #[doc(hidden)] な公開項目に doc
コメントが付いていること、既知のどのパッケージにも属さない Rust ソースが無いことの
3つである。check-doc-comments は、内部領域をハードコードした一覧ではなく、走査
対象パッケージ (crates 配下・examples 配下・xtask・verification 配下のうち
Cargo.toml を持つディレクトリ) それぞれの Cargo.toml から機械的に導出する
(issue #32)。`[package] publish = false`(空配列を含む)か `[lib] proc-macro = true`
(下線表記を含む)を持つパッケージを内部領域とみなし、publish が真偽値・配列の
どちらでもない場合 (ワークスペース継承を含む) と Cargo.toml が読めない・構文解析
できない場合はエラーで打ち切る。check-doc-comments は、公開面と判定したパッケージも
報告へ1行ずつ出し、内部領域の件数と合わせて総数を突き合わせられるようにする。

check-doc-comments が対象外にするもの: crates/graphite の公開面 (rustc の
#![warn(missing_docs)] が別に検査する)、生成コードの公開面、graphite-macros の
#[proc_macro] 系の関数 (Cargo.toml の設定では内部領域と判定される中にありながら
利用者の rustdoc に出るため撤去しない)、ファイル冒頭の `//!`、マクロ呼び出しの
トークン列の中に書かれた doc コメント、#[doc(hidden)] が付いた項目とその中身。

check-doc-comments が検査しないもの: doc コメントの中身が項目の説明として正しいか、
クレート境界を越えた再公開 (pub use) による公開到達性 (囲むモジュールが全て pub で
あることだけで判定する)、タプル構造体の名前を持たないフィールド、private な型に
対する inherent impl の pub なメソッド (公開項目として数える)。

`xtask/tests/doc_comments_check.rs` がこの検査を呼ぶため、
`cargo test --workspace` も同じ違反を検出する。

check-line-counts が検査するもの: 台帳 (docs/development/line_count_ledger.md) と
実際のコード行数の両方である。check-line-counts は8種類の違反を報告する。台帳に
無いのに100行を超えているファイル、150行の上限を超えているファイル、台帳にあるのに
100行以内へ収まったファイル、台帳にありながら検査対象に実在しない綴り、台帳の区分と
根拠から組み立てた定型の文を冒頭コメントが書いていないファイル、台帳に無いのに
冒頭コメントが例外を名乗っているファイル、読み込みに失敗したファイル、台帳の行として
読めない表の行である。check-line-counts は報告へ、数えたファイル数・台帳の件数・
再設計待ちの件数を出す。

コード行の数え方・区分の定義・数え方が持つ3つの限界 (生文字列・文字リテラル・
ブロックコメントの入れ子の扱い) は docs/development/line_count_ledger.md が正本
である。check-line-counts は空行とコメントだけの行を数えず、#[cfg(test)] を付けた
テストモジュールの中は数える。check-line-counts は150行の上限を区分「宣言的データ
リテラル」へ適用せず、区分「再設計待ち」は当面の猶予として件数だけを報告する。

check-line-counts が対象外にするもの: ディレクトリ名が generated・target の場所に
あるファイル、crates・xtask・examples・verification の外にあるファイル、拡張子が
.rs でないファイル。

check-line-counts が検査しないもの: 台帳に書かれた根拠がファイルの実際の構造と
合っていること (人が読んで判定する)、台帳の行数 (検査器が数えるため台帳は持たない)、
関数50行の原則。

`cargo test --workspace` からは呼ばない。150行を超える再設計待ちのファイルが残って
いる間は、通常のテスト実行を落とし続けることになるためである。接続は issue #28 の
やること4 (再設計待ちを0件にする) の完了後に行う。
";
